#!/usr/bin/env node
/**
 * Generate message-keys.generated.ts from locales/en.json (keys-only union).
 */
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { readLocaleJsonFile, WEB_LOCALES_DIR } from "./i18n-catalog-utils.mjs";

const repoRoot = resolve(import.meta.dirname, "..");

/** @param {string} packageName @param {string} localesDir @param {string} outPath */
function codegenPackage(packageName, localesDir, outPath) {
  const en = readLocaleJsonFile(localesDir, "en");
  const keys = Object.keys(en).sort();
  const union = keys.map((key) => JSON.stringify(key)).join(" | ");
  const content = `/** Generated by pnpm i18n:codegen - do not edit. */\nexport type MessageKey = ${union || "never"};\n`;
  writeFileSync(outPath, content, "utf8");
  console.log(`i18n:codegen: ${packageName} (${keys.length} keys) → ${outPath}`);
}

codegenPackage(
  "web",
  WEB_LOCALES_DIR,
  join(repoRoot, "packages/web/app/i18n/message-keys.generated.ts"),
);

codegenPackage(
  "marketing",
  join(repoRoot, "packages/marketing/src/i18n/locales"),
  join(repoRoot, "packages/marketing/src/i18n/message-keys.generated.ts"),
);
