-- The removal of one bookmark by whoever holds the database (doc 05 sections 2.2, 2.9 and 3.3, doc 10 section 2.10, T1, T2 and T15,
-- doc 02 section 11.1): an operator who must remove a bookmark, whatever its owner, an ownerless "Former member" bookmark included, for
-- which sys_bookmark_delete answers false. The function is entered in src/system/registry.ts, as an operator operation: slugbase_app and PUBLIC
-- cannot execute it, so no request, job or console action reaches it, and the migration login reaches it with SET ROLE slugbase_system
-- (docs/self-hosting/remove-bookmark.md). slugbase_owner creates it and hands it to slugbase_system, which needs CREATE on the schema for
-- the length of that statement.
GRANT CREATE ON SCHEMA public TO slugbase_system;

-- sys_bookmark_operator_delete(workspace_id, bookmark_id, event_id, reason): deletes the bookmark of the workspace whoever owns it, gives its
-- place under bookmarks.max back and writes the audit event that records it, in the calling transaction. The counter falls only together
-- with the row it counted, and only for a bookmark that is not plan-archived, exactly as sys_bookmark_delete has it; the rows that reference
-- the bookmark (filings, shares, tag links, remembered /go choices) go by foreign key, and the slug, forwarding, the pin and the usage
-- counters are columns of the row. The workspace's row is locked (FOR NO KEY UPDATE) before the bookmark's, the lock order of
-- sys_bookmark_delete and of a member's removal. A bookmark of another workspace, one that is gone, and any bookmark of a workspace being
-- deleted or that does not exist answer false and write nothing. The counter's CHECK refuses a count below zero, so a counter that disagrees
-- with the rows fails the call instead of passing silently.
--
-- The event is 'bookmark.operator_deleted' in the workspace's own log, so the owners and admins who read it see that the operator acted
-- (T15): the actor is the system, labelled with the login the call was made with (session_user, which SET ROLE does not change), the entity
-- is the bookmark (its identifier only: no title, URL or slug) and the metadata holds the reason, trimmed, 1 to 100 characters without a
-- control character, which the workspace's admins read. The caller supplies the event identifier: an identifier is generated by the
-- application (Q91), never by the database, and an operator at a SQL prompt is the caller here; the log orders by (created_at, id), so it
-- need not be a UUIDv7. No argument may be NULL and a reason that does not fit raises invalid_parameter_value, with nothing written.
CREATE OR REPLACE FUNCTION public.sys_bookmark_operator_delete(p_workspace_id uuid, p_bookmark_id uuid, p_event_id uuid, p_reason text) RETURNS boolean
  LANGUAGE plpgsql VOLATILE SECURITY DEFINER
  SET search_path = pg_catalog, public, pg_temp
  AS $$
DECLARE
  v_reason text;
  v_archived_at timestamptz;
BEGIN
  IF p_workspace_id IS NULL OR p_bookmark_id IS NULL OR p_event_id IS NULL OR p_reason IS NULL THEN
    RAISE EXCEPTION 'sys_bookmark_operator_delete needs a workspace, a bookmark, an event identifier and a reason'
      USING ERRCODE = 'invalid_parameter_value';
  END IF;
  v_reason := btrim(p_reason);
  IF p_reason ~ '[\u0001-\u001f\u007f-\u009f\u2028\u2029]' OR length(v_reason) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION 'the reason of sys_bookmark_operator_delete is 1 to 100 characters without a control character'
      USING ERRCODE = 'invalid_parameter_value';
  END IF;

  PERFORM 1 FROM public.workspaces w
  WHERE w.id = p_workspace_id AND w.deleting_at IS NULL
  FOR NO KEY UPDATE;
  IF NOT FOUND THEN
    RETURN false;
  END IF;

  DELETE FROM public.bookmarks b
  WHERE b.id = p_bookmark_id AND b.workspace_id = p_workspace_id
  RETURNING b.plan_archived_at INTO v_archived_at;
  IF NOT FOUND THEN
    RETURN false;
  END IF;

  IF v_archived_at IS NULL THEN
    UPDATE public.workspaces SET bookmark_count = bookmark_count - 1 WHERE id = p_workspace_id;
  END IF;

  INSERT INTO public.audit_events (id, workspace_id, actor_type, actor_account_id, actor_label, action, entity_type, entity_id, metadata, ip_prefix)
  VALUES (p_event_id, p_workspace_id, 'system', NULL, session_user::text, 'bookmark.operator_deleted', 'bookmark', p_bookmark_id,
          jsonb_build_object('reason', v_reason), NULL);
  RETURN true;
END
$$;

ALTER FUNCTION public.sys_bookmark_operator_delete(uuid, uuid, uuid, text) OWNER TO slugbase_system;
REVOKE CREATE ON SCHEMA public FROM slugbase_system;

REVOKE ALL ON FUNCTION public.sys_bookmark_operator_delete(uuid, uuid, uuid, text) FROM PUBLIC;
