import { sql } from "drizzle-orm";
import { bigint, boolean, check, foreignKey, index, integer, pgTable, text, timestamp, unique, uniqueIndex, uuid, type UpdateDeleteAction } from "drizzle-orm/pg-core";
import { tsvector } from "./types.ts";
import { workspaceMembers, workspaces } from "./workspaces.ts";

// `bookmarks` of doc 05 section 2.4. Row-level security, the policies, the privileges of `slugbase_app` and the updated_at
// trigger live in src/sql/470-bookmarks.sql, and the grants and the departure trigger of the slug in src/sql/560-bookmark-slugs.sql. The list, slug and search indexes are the ones below; the search indexes serve `sys_search` (src/sql/590-search.sql).

// The action of the owner's foreign key. A member who leaves takes the ownership with them and not the bookmark, so only
// `owner_id` is cleared: the key shares `workspace_id`, which is NOT NULL, and a plain `SET NULL` would clear that too and
// refuse to delete the membership. PostgreSQL 15 puts the columns to clear after the action. drizzle-orm's `onDelete` types a
// closed list without them, but drizzle-kit copies the string into the migration as it is, which is the only way to get the
// constraint into a generated migration (a statement in src/sql would be repeated by every migration that carries that
// directory). The merged migration keeps the form `SET DEFAULT (owner_id)`, which clears the same column because `owner_id`
// has no default; `SET NULL (owner_id)` is equivalent, and the expand/contract check of `pnpm db:check` reads both. The column
// must therefore never be given a default.
const CLEAR_OWNER = "set default (owner_id)" as UpdateDeleteAction;

/**
 * A bookmark of a workspace, owned by one of its members. `url` is the normalised URL as stored and `url_canonical` the key of
 * duplicate detection and of the metadata and AI caches (`packages/core/src/bookmarks/url.ts` makes both); the table refuses any
 * URL that is not `http` or `https`. A member who leaves the workspace leaves their bookmarks with it: `owner_id` becomes NULL
 * (doc 02 section 3.5). `slug` is `text`, not `citext`, holding the lower-case form that the application writes (`citext_eq` is not leakproof, so a `citext` comparison could not be an
 * index condition of `bookmarks_slug_idx` under row-level security, doc 05 section 4); the CHECK refuses anything outside the grammar. `search` is generated by the database from the slug, title, host and description; the slug term is
 * wrapped in `coalesce`, since a bookmark without a slug would otherwise have no search document at all.
 */
export const bookmarks = pgTable(
  "bookmarks",
  {
    id: uuid().primaryKey(),
    workspaceId: uuid()
      .notNull()
      .references(() => workspaces.id, { onDelete: "cascade" }),
    ownerId: uuid(),
    url: text().notNull(),
    urlCanonical: text().notNull(),
    host: text().notNull(),
    title: text().notNull(),
    description: text(),
    slug: text(),
    forwarding: boolean().notNull().default(false),
    /** When the bookmark was pinned; null when it is not. */
    pinnedAt: timestamp({ withTimezone: true }),
    /** Set by downgrade handling only; an archived bookmark is excluded from every product query and from `workspaces.bookmark_count`. */
    planArchivedAt: timestamp({ withTimezone: true }),
    openCount: bigint({ mode: "number" }).notNull().default(0),
    lastOpenedAt: timestamp({ withTimezone: true }),
    search: tsvector().generatedAlwaysAs(
      sql`setweight(to_tsvector('simple', coalesce(slug, '')), 'A') || setweight(to_tsvector('simple', title), 'A') || setweight(to_tsvector('simple', host), 'B') || setweight(to_tsvector('simple', coalesce(description, '')), 'C')`,
    ),
    /** The `ETag` of the bookmark. */
    version: integer().notNull().default(1),
    createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    unique("bookmarks_workspace_id_id_key").on(table.workspaceId, table.id),
    foreignKey({
      name: "bookmarks_owner_fkey",
      columns: [table.workspaceId, table.ownerId],
      foreignColumns: [workspaceMembers.workspaceId, workspaceMembers.accountId],
    }).onDelete(CLEAR_OWNER),
    check("bookmarks_url_scheme_check", sql`${table.url} ~* '^https?://'`),
    check("bookmarks_url_length_check", sql`length(${table.url}) <= 2048`),
    check("bookmarks_title_check", sql`length(${table.title}) BETWEEN 1 AND 300`),
    check("bookmarks_description_check", sql`length(${table.description}) <= 1000`),
    check("bookmarks_slug_check", sql`${table.slug}::text ~ '^[a-z0-9][a-z0-9-]{0,63}$'`),
    check("bookmarks_forwarding_check", sql`NOT ${table.forwarding} OR ${table.slug} IS NOT NULL`),
    // The slug indexes of doc 05 section 2.4. drizzle-kit has no builder for `INCLUDE` or `NULLS NOT DISTINCT` on an index with a `WHERE`, so the
    // last column of each is a raw fragment that closes the column list and writes the rest of the statement, ending in the opening of the
    // parenthesis the generator closes. The statements it emits are the ones in the migration (`pnpm db:generate` writes them, `pnpm db:check` finds no drift).
    uniqueIndex("bookmarks_owner_slug_key").on(table.workspaceId, table.ownerId, sql.raw("slug) NULLS NOT DISTINCT WHERE (slug IS NOT NULL")),
    index("bookmarks_slug_idx").on(table.workspaceId, sql.raw("slug) INCLUDE (id, owner_id, url, forwarding, plan_archived_at) WHERE (slug IS NOT NULL")),
    // The search indexes of doc 05 section 2.4, built non-blocking by the migration that adds them: the full-text index over `search`, and the trigram indexes of the slug, the title and the host
    // (the host's is what the trigram similarity on title and host needs). `sys_search` reads them as slugbase_system, which bypasses the policy, so the operators `@@`, `<%` and `LIKE` are index conditions.
    index("bookmarks_search_idx").using("gin", table.workspaceId, table.search),
    // The title and slug vector alone, which is the expression of the first two weights of `search`: `sys_search` finds every title and slug match through it and ranks them exactly, and fills the
    // rest of the answer from a bounded window of the host and description matches of `bookmarks_search_idx`.
    index("bookmarks_title_slug_search_idx").using(
      "gin",
      table.workspaceId,
      sql`(to_tsvector('simple', coalesce(${table.slug}, '')) || to_tsvector('simple', ${table.title}))`,
    ),
    index("bookmarks_slug_trgm_idx").using("gin", table.workspaceId, table.slug.op("gin_trgm_ops")),
    index("bookmarks_title_trgm_idx").using("gin", table.workspaceId, table.title.op("gin_trgm_ops")),
    index("bookmarks_host_trgm_idx").using("gin", table.workspaceId, table.host.op("gin_trgm_ops")),
    // The list indexes of doc 05 section 2.4: one per sort of `GET /bookmarks`, each ending in `id` as the tiebreak of its keyset.
    index("bookmarks_owner_recent_idx")
      .on(table.workspaceId, table.ownerId, table.createdAt.desc(), table.id.desc())
      .where(sql`${table.planArchivedAt} IS NULL`),
    index("bookmarks_owner_opened_idx")
      .on(table.workspaceId, table.ownerId, table.lastOpenedAt.desc().nullsLast(), table.id.desc())
      .where(sql`${table.planArchivedAt} IS NULL`),
    index("bookmarks_owner_popular_idx")
      .on(table.workspaceId, table.ownerId, table.openCount.desc(), table.id.desc())
      .where(sql`${table.planArchivedAt} IS NULL`),
    index("bookmarks_owner_title_idx").on(table.workspaceId, table.ownerId, sql`lower(${table.title})`, table.id),
    index("bookmarks_pinned_idx")
      .on(table.workspaceId, table.ownerId, table.pinnedAt.desc())
      .where(sql`${table.pinnedAt} IS NOT NULL AND ${table.planArchivedAt} IS NULL`),
  ],
);
