import { sql } from "drizzle-orm";
import { enqueueInTenantTransaction, type QueuedJob } from "../system/queue.ts";
import type { MemberRole } from "../schema/workspaces.ts";
import { tenantHandle, type TenantTx } from "../tenant.ts";

// The workspaces of the signed-in account, in an account-level transaction (doc 05 sections 2.2 and 3.3,
// doc 04 section 10.4). The list reads the account's own membership rows, whose workspaces the `workspaces`
// policy shows through `app_member_workspace_ids()`, and the member count of each from
// `app_member_workspace_counts()`, which counts the members of the workspaces the account belongs to and
// shows no member's identity. A workspace is created by the system operation `sys_create_workspace`; the
// account it makes the owner is always the one `withTenant` was opened for, never one the caller passes, and
// the operation itself refuses another account while a tenant account is set.

/** One workspace the account is a member of. */
export interface WorkspaceSummary {
  readonly id: string;
  readonly name: string;
  /** The account's role in it. */
  readonly role: MemberRole;
  readonly memberCount: number;
}

export interface NewWorkspace {
  /** A UUIDv7 generated by the caller. */
  readonly id: string;
  /** 1 to 64 characters. */
  readonly name: string;
  /** Jobs queued in the same transaction, only when the workspace is created. */
  readonly jobs: readonly QueuedJob[];
}

export interface WorkspaceRepository {
  /**
   * The workspaces of the account of the transaction that are not being deleted, the most recently active
   * first: by the membership's `last_active_at` (never active last), then `joined_at` (newest first), then
   * the workspace id. Works in an account-level transaction.
   */
  list(): Promise<readonly WorkspaceSummary[]>;
  /**
   * Creates the workspace with the account of the transaction as its owner and its settings row, and queues
   * the jobs, in the open transaction. False, with nothing written, when the account does not exist or is
   * disabled.
   */
  create(workspace: NewWorkspace): Promise<boolean>;
}

interface ListedRow extends Record<string, unknown> {
  id: string;
  name: string;
  role: string;
  member_count: string;
}

interface CreatedRow extends Record<string, unknown> {
  created: boolean;
}

function roleOf(value: string): MemberRole {
  if (value === "owner" || value === "admin" || value === "member") {
    return value;
  }
  throw new Error("workspace_members.role holds a value outside owner, admin and member");
}

export function workspaceRepository(tx: TenantTx): WorkspaceRepository {
  return {
    async list() {
      const rows = await tenantHandle(tx).execute<ListedRow>(sql`
        SELECT w.id, w.name, m.role::text AS role, c.member_count::text AS member_count
        FROM public.workspace_members m
        JOIN public.workspaces w ON w.id = m.workspace_id
        JOIN public.app_member_workspace_counts() c ON c.workspace_id = w.id
        WHERE m.account_id = ${tx.accountId}::uuid
          AND w.id IN (SELECT public.app_member_workspace_ids())
        ORDER BY m.last_active_at DESC NULLS LAST, m.joined_at DESC, w.id`);
      return rows.map((row) => ({ id: row.id, name: row.name, role: roleOf(row.role), memberCount: Number(row.member_count) }));
    },

    async create(workspace) {
      const rows = await tenantHandle(tx).execute<CreatedRow>(sql`
        SELECT public.sys_create_workspace(${tx.accountId}::uuid, ${workspace.id}::uuid, ${workspace.name}::text) AS created`);
      const row = rows[0];
      if (rows.length !== 1 || row === undefined) {
        throw new Error("sys_create_workspace did not return exactly one row");
      }
      if (!row.created) {
        return false;
      }
      for (const job of workspace.jobs) {
        await enqueueInTenantTransaction(tx, job);
      }
      return true;
    },
  };
}
