import { and, count, desc, eq, isNull, lt, or, sql } from "drizzle-orm";
import { accounts } from "../schema/accounts.ts";
import { apiTokens } from "../schema/api-tokens.ts";
import { workspaceMembers, workspaces } from "../schema/workspaces.ts";
import { tenantHandle, type TenantTx } from "../tenant.ts";

// The account's personal API tokens (doc 05 section 2.1, doc 04 section 10.3),
// managed in an account-level transaction on the account policy of `api_tokens`
// (T1): an account lists, creates and revokes its own tokens only, whatever
// workspace a token is bound to, and `slugbase_app` can read no hash. The
// account predicate here is the application layer on top of that.

export type ApiTokenScope = "read" | "read-write";

/** A token as it is shown: never the hash and never the secret. */
export interface ApiTokenRecord {
  readonly id: string;
  readonly name: string;
  readonly workspaceId: string;
  readonly workspaceName: string;
  readonly scope: ApiTokenScope;
  /** The first characters of the token after `slb_`. */
  readonly prefix: string;
  readonly createdAt: Date;
  /** When the token last authenticated a request; null when it never has. */
  readonly lastUsedAt: Date | null;
  /** Null when the token never expires. */
  readonly expiresAt: Date | null;
}

export interface NewApiToken {
  /** The identifier, generated by the application (UUIDv7). */
  readonly id: string;
  /** The workspace the token is bound to; the account must be a member of it. */
  readonly workspaceId: string;
  readonly name: string;
  readonly scope: ApiTokenScope;
  /** SHA-256 of the token, 32 bytes. */
  readonly tokenHash: Buffer;
  readonly tokenPrefix: string;
  /** Whole days from now, on the database clock; null for a token that never expires. */
  readonly expiresInDays: number | null;
  /** The most tokens the account may hold that are neither revoked nor expired. */
  readonly limit: number;
}

export type ApiTokenCreation =
  | { readonly kind: "created"; readonly token: ApiTokenRecord }
  /** The account is not a member of the workspace, or the workspace is being deleted or does not exist; the three are not told apart. */
  | { readonly kind: "not_a_member" }
  | { readonly kind: "limit_reached" }
  | { readonly kind: "name_taken" };

export interface ApiTokenRepository {
  /**
   * The account's tokens that are not revoked, newest first, `limit` of them after the token `afterId`
   * (the first page when null). Tokens bound to a workspace that is being deleted are not listed.
   */
  list(afterId: string | null, limit: number): Promise<readonly ApiTokenRecord[]>;
  /**
   * Stores a new token. The checks and the insert run under a lock on the account's row, so two
   * creations at once cannot both pass the limit or the name check. Nothing is written for any outcome
   * but `created`.
   */
  create(token: NewApiToken): Promise<ApiTokenCreation>;
  /**
   * Revokes the account's token with this id and says whether the account has one: true also when it was
   * revoked before, which keeps the time of the first revocation. False for an id the account does not
   * hold, another account's included.
   */
  revoke(id: string): Promise<boolean>;
}

type ListedRow = {
  id: string;
  name: string;
  workspaceId: string;
  workspaceName: string;
  scope: string;
  prefix: string;
  createdAt: Date;
  lastUsedAt: Date | null;
  expiresAt: Date | null;
};

const SCOPES: readonly ApiTokenScope[] = ["read", "read-write"];

// The CHECK constraint of the column holds the value to these two; anything else is schema drift.
function scopeOf(value: string): ApiTokenScope {
  const found = SCOPES.find((candidate) => candidate === value);
  if (found === undefined) {
    throw new Error("api_tokens.scope holds a value outside read, read-write");
  }
  return found;
}

function recordOf(row: ListedRow): ApiTokenRecord {
  return { ...row, scope: scopeOf(row.scope) };
}

const shown = {
  id: apiTokens.id,
  name: apiTokens.name,
  workspaceId: apiTokens.workspaceId,
  workspaceName: workspaces.name,
  scope: apiTokens.scope,
  prefix: apiTokens.tokenPrefix,
  createdAt: apiTokens.createdAt,
  lastUsedAt: apiTokens.lastUsedAt,
  expiresAt: apiTokens.expiresAt,
};

export function apiTokenRepository(tx: TenantTx): ApiTokenRepository {
  return {
    async list(afterId, limit) {
      const handle = tenantHandle(tx);
      const rows = await handle
        .select(shown)
        .from(apiTokens)
        .innerJoin(workspaces, eq(workspaces.id, apiTokens.workspaceId))
        .where(and(eq(apiTokens.accountId, tx.accountId), isNull(apiTokens.revokedAt), afterId === null ? undefined : lt(apiTokens.id, afterId)))
        .orderBy(desc(apiTokens.id))
        .limit(limit);
      return rows.map(recordOf);
    },

    async create(token) {
      const handle = tenantHandle(tx);
      // The account's row is the lock the whole check-then-insert sequence is serialised on.
      await handle.select({ id: accounts.id }).from(accounts).where(eq(accounts.id, tx.accountId)).for("update");

      const membership = await handle
        .select({ workspaceId: workspaceMembers.workspaceId })
        .from(workspaceMembers)
        .innerJoin(workspaces, eq(workspaces.id, workspaceMembers.workspaceId))
        .where(and(eq(workspaceMembers.accountId, tx.accountId), eq(workspaceMembers.workspaceId, token.workspaceId), isNull(workspaces.deletingAt)));
      if (membership.length === 0) {
        return { kind: "not_a_member" };
      }

      const taken = await handle
        .select({ id: apiTokens.id })
        .from(apiTokens)
        .where(and(eq(apiTokens.accountId, tx.accountId), eq(apiTokens.name, token.name), isNull(apiTokens.revokedAt)));
      if (taken.length > 0) {
        return { kind: "name_taken" };
      }

      const [active] = await handle
        .select({ total: count() })
        .from(apiTokens)
        .where(
          and(
            eq(apiTokens.accountId, tx.accountId),
            isNull(apiTokens.revokedAt),
            or(isNull(apiTokens.expiresAt), sql`${apiTokens.expiresAt} > now()`),
          ),
        );
      if ((active?.total ?? 0) >= token.limit) {
        return { kind: "limit_reached" };
      }

      // A statement of its own, not `handle.insert(apiTokens)`: Drizzle names every column of the table in
      // the column list and gives the ones it has no value for DEFAULT, and `slugbase_app` may insert only the
      // columns named here (src/sql/150-api-tokens.sql), so a column list naming `revoked_at` would be refused.
      const expiresAt = token.expiresInDays === null ? sql`NULL` : sql`now() + make_interval(days => ${token.expiresInDays})`;
      await handle.execute(sql`
        INSERT INTO api_tokens (id, account_id, workspace_id, name, token_hash, token_prefix, scope, expires_at)
        VALUES (${token.id}, ${tx.accountId}, ${token.workspaceId}, ${token.name}, ${token.tokenHash}, ${token.tokenPrefix}, ${token.scope}, ${expiresAt})`);
      const [stored] = await handle
        .select(shown)
        .from(apiTokens)
        .innerJoin(workspaces, eq(workspaces.id, apiTokens.workspaceId))
        .where(and(eq(apiTokens.id, token.id), eq(apiTokens.accountId, tx.accountId)));
      if (stored === undefined) {
        throw new Error("a token stored in the transaction was not found in it");
      }
      return { kind: "created", token: recordOf(stored) };
    },

    async revoke(id) {
      const handle = tenantHandle(tx);
      const written = await handle
        .update(apiTokens)
        .set({ revokedAt: sql`coalesce(${apiTokens.revokedAt}, now())` })
        .where(and(eq(apiTokens.id, id), eq(apiTokens.accountId, tx.accountId)))
        .returning({ id: apiTokens.id });
      return written.length === 1;
    },
  };
}
