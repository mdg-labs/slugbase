import type { CredentialTokenPurpose } from "@slugbase/core";
import { sql } from "drizzle-orm";
import { tenantHandle, type TenantTx } from "../tenant.ts";

// Issuing an emailed single-use token to the account of the transaction (doc 05 sections 2.1 and 3.3). The
// table is closed to `slugbase_app`, so the issue is the system operation `sys_credential_token_issue`; the
// account it names is always the one `withTenant` was opened for, never one the caller passes. Redeeming a
// token is anonymous and arrives with the operations that redeem one.

const TOKEN_HASH_BYTES = 32;

export interface NewCredentialToken {
  /** A UUIDv7 generated by the caller. */
  readonly id: string;
  readonly purpose: CredentialTokenPurpose;
  /** SHA-256 of the token the link carries; the token itself is never given to the database. */
  readonly tokenHash: Buffer;
  /** The address an `email_change` token moves the account to; null for every other purpose. */
  readonly targetEmail: string | null;
  /** How long the token works, from now on the database clock: 1 second to 7 days. */
  readonly ttlSeconds: number;
}

export interface CredentialTokenRepository {
  /**
   * Stores the token for the account of the transaction and deletes that account's older unused tokens of
   * the same purpose, in one call. False, with nothing changed, when the account does not exist or is disabled.
   */
  issue(token: NewCredentialToken): Promise<boolean>;
}

export function credentialTokenRepository(tx: TenantTx): CredentialTokenRepository {
  return {
    async issue(token) {
      if (token.tokenHash.length !== TOKEN_HASH_BYTES) {
        throw new RangeError(`tokenHash must be a ${String(TOKEN_HASH_BYTES)}-byte SHA-256 digest`);
      }
      const rows = await tenantHandle(tx).execute<{ issued: boolean | null }>(sql`
        SELECT public.sys_credential_token_issue(
          ${token.id}::uuid,
          ${token.purpose}::text,
          ${tx.accountId}::uuid,
          ${token.tokenHash}::bytea,
          ${token.targetEmail}::text,
          ${token.ttlSeconds}::integer) AS issued`);
      const issued = rows[0]?.issued;
      if (typeof issued !== "boolean") {
        throw new Error("sys_credential_token_issue did not answer with a flag");
      }
      return issued;
    },
  };
}
