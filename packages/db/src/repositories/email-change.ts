import type { CredentialTokenPurpose } from "@slugbase/core";
import { sql } from "drizzle-orm";
import { tenantHandle, type TenantTx } from "../tenant.ts";

// Issuing the emailed tokens of an email change to the account of the transaction (doc 05 sections 2.1 and 3.3, doc
// 02 section 2.6, doc 10 T8). The table is closed to `slugbase_app`, so the issue is the system operation
// `sys_email_change_token_issue`; the account it names is always the one `withTenant` was opened for, never one the
// caller passes. The operation, not the caller, decides whether the pending address may be mailed to.

const TOKEN_HASH_BYTES = 32;

export interface NewEmailChangeToken {
  /** A UUIDv7 generated by the caller. */
  readonly id: string;
  /** `email_change` for the confirmation mailed to the new address, `email_change_cancel` for the notice's link. */
  readonly purpose: Extract<CredentialTokenPurpose, "email_change" | "email_change_cancel">;
  /** SHA-256 of the token the link carries; the token itself is never given to the database. */
  readonly tokenHash: Buffer;
  /** How long the token works, from now on the database clock: 1 second to 7 days. */
  readonly ttlSeconds: number;
}

export interface EmailChangeRepository {
  /**
   * Stores the token for the account of the transaction and answers the address its pending change moves to,
   * replacing the account's older unused token of the purpose. Undefined, with nothing stored, when no change
   * is pending, the account is disabled or was never verified and, for a confirmation, when the pending
   * address is the account's own or belongs to another account.
   */
  issue(token: NewEmailChangeToken): Promise<string | undefined>;
}

export function emailChangeRepository(tx: TenantTx): EmailChangeRepository {
  return {
    async issue(token) {
      if (token.tokenHash.length !== TOKEN_HASH_BYTES) {
        throw new RangeError(`tokenHash must be a ${String(TOKEN_HASH_BYTES)}-byte SHA-256 digest`);
      }
      const rows = await tenantHandle(tx).execute<{ pending: string | null }>(sql`
        SELECT public.sys_email_change_token_issue(
          ${token.id}::uuid,
          ${token.purpose}::text,
          ${tx.accountId}::uuid,
          ${token.tokenHash}::bytea,
          ${token.ttlSeconds}::integer) AS pending`);
      const row = rows[0];
      if (rows.length !== 1 || row === undefined) {
        throw new Error("sys_email_change_token_issue did not return exactly one row");
      }
      return row.pending ?? undefined;
    },
  };
}
