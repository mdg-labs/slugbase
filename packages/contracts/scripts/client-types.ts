import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";

/** The `paths` and `components` types of an OpenAPI document, as the committed `schema.d.ts`. */
export async function renderClientTypes(openApiText: string): Promise<string> {
  const ast = await openapiTS(JSON.parse(openApiText) as OpenAPI3);
  return `/** Generated by \`pnpm api:gen\` from openapi.json. Do not edit. */\n\n${astToString(ast)}`;
}
