import type { AuditWriter } from "../audit/writer.ts";
import type { DomainEvent } from "../events/catalog.ts";

// Creating a workspace (doc 02 section 3.2, doc 04 section 10.4): any verified account may, where the
// deployment lets accounts create workspaces, and the creator becomes its owner. Creating one is a system
// operation (`sys_create_workspace`, doc 05 section 3.3), which the store behind this port reaches; the
// service decides who may, what is recorded and what is announced, and never reports a workspace the
// store did not make. The deployment's answer to "may accounts create workspaces" is a plain value the
// caller resolves (the composition root's default, later the instance setting): no edition decides it (D4).

/** The longest workspace name, in characters (doc 02 section 3.1). */
export const WORKSPACE_NAME_MAX_LENGTH = 64;

export interface WorkspaceCreationPolicy {
  /** Whether the deployment lets ordinary accounts create workspaces. */
  readonly creationAllowed: boolean;
  readonly emailVerified: boolean;
}

/** Whether the account can create a workspace, which is also what the workspace list reports so the UI can hide the action. */
export function canCreateWorkspace({ creationAllowed, emailVerified }: WorkspaceCreationPolicy): boolean {
  return creationAllowed && emailVerified;
}

export interface WorkspaceCreationRequest {
  /** The account the workspace is made for and which becomes its owner; the account that asked. */
  readonly accountId: string;
  /** A UUIDv7 generated by the caller (Q91). */
  readonly workspaceId: string;
  readonly name: string;
  /** Announced in the transaction that creates the workspace, and only when it does. */
  readonly events: readonly DomainEvent<"workspace.created">[];
}

export interface WorkspaceStore {
  /**
   * Creates the workspace, its owner membership and its settings, and records the events, in the
   * transaction the store is bound to. False, with nothing written, for an account that does not exist
   * or is disabled.
   */
  create(request: WorkspaceCreationRequest): Promise<boolean>;
}

export interface WorkspaceCreationDependencies {
  readonly store: WorkspaceStore;
  /** Bound to the same transaction as the store. */
  readonly audit: AuditWriter;
  /** A fresh UUIDv7. */
  readonly newId: () => string;
}

export interface WorkspaceCreationAsk extends WorkspaceCreationPolicy {
  readonly accountId: string;
  /** The account's display name, kept in the audit row as the label of the actor. */
  readonly displayName: string;
  readonly name: string;
  /** The coarse network of the request, null when unknown. */
  readonly ipPrefix: string | null;
}

export type WorkspaceCreationOutcome =
  | { readonly kind: "created"; readonly workspaceId: string }
  /** The deployment does not let accounts create workspaces. */
  | { readonly kind: "not_allowed" }
  | { readonly kind: "unverified" }
  /** The account does not exist or is disabled. */
  | { readonly kind: "unavailable" };

/**
 * Creates the workspace and writes `workspace.created` to its audit log, both in the transaction the
 * stores are bound to, so the audit row exists exactly when the workspace does. A refusal writes
 * nothing; a failure of either write rejects and the caller's transaction must not commit.
 */
export async function createWorkspace(
  { store, audit, newId }: WorkspaceCreationDependencies,
  ask: WorkspaceCreationAsk,
): Promise<WorkspaceCreationOutcome> {
  if (!ask.creationAllowed) {
    return { kind: "not_allowed" };
  }
  if (!ask.emailVerified) {
    return { kind: "unverified" };
  }
  const length = Array.from(ask.name).length;
  if (length < 1 || length > WORKSPACE_NAME_MAX_LENGTH) {
    throw new RangeError(`a workspace name has 1 to ${String(WORKSPACE_NAME_MAX_LENGTH)} characters`);
  }

  const workspaceId = newId();
  const created = await store.create({
    accountId: ask.accountId,
    workspaceId,
    name: ask.name,
    events: [{ eventId: newId(), name: "workspace.created", payload: { workspaceId, accountId: ask.accountId } }],
  });
  if (!created) {
    return { kind: "unavailable" };
  }
  await audit.write({
    action: "workspace.created",
    workspaceId,
    actor: { type: "account", accountId: ask.accountId, label: ask.displayName },
    entity: { type: "workspace", id: workspaceId },
    metadata: { name: ask.name },
    ipPrefix: ask.ipPrefix,
  });
  return { kind: "created", workspaceId };
}
