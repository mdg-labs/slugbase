import { prepareAuditRecord, type AuditRecord } from "../audit/writer.ts";
import type { DomainEvent } from "../events/catalog.ts";

// The personal workspace of an account that registered itself (doc 02 section 2.2): "<display name>'s
// workspace", created once, with the account as its owner, when the address is verified or, on a
// deployment that does not require verification, when the account is registered. Creating a workspace
// is a system operation (`sys_create_workspace`, doc 05 section 3.3), which the store behind this port
// reaches; the service decides what is created and announced, and refuses to report a workspace it did not get.

/** What the personal name ends with; the store puts the account's display name in front of it, cut to fit the 64 characters a workspace name may have. */
export const PERSONAL_WORKSPACE_NAME_SUFFIX = "'s workspace";

/** `created`: the workspace was made. `exists`: the account already owns a workspace, and nothing was written. */
export type PersonalWorkspaceOutcome = "created" | "exists";

export interface PersonalWorkspaceRequest {
  readonly accountId: string;
  /** A UUIDv7 generated by the caller (Q91). */
  readonly workspaceId: string;
  readonly nameSuffix: string;
  /** Announced in the transaction that creates the workspace, and only when it does. */
  readonly events: readonly DomainEvent<"workspace.created">[];
  /**
   * Builds the `workspace.created` audit event of the workspace once the store has created it and knows the name it
   * got; the store writes it in the same transaction, and only when it creates the workspace.
   */
  readonly audit: (created: { readonly name: string; readonly displayName: string }) => AuditRecord;
}

export interface PersonalWorkspaceStore {
  /**
   * Creates the workspace, its owner membership and its settings, and records the events and the audit event, in the transaction
   * the store is bound to, unless the account already owns a workspace. Resolves to undefined, with nothing
   * written, for an account that does not exist or is disabled.
   */
  create(request: PersonalWorkspaceRequest): Promise<PersonalWorkspaceOutcome | undefined>;
}

export interface PersonalWorkspaceDependencies {
  readonly store: PersonalWorkspaceStore;
  /** A fresh UUIDv7. */
  readonly newId: () => string;
}

/** The account to provision for does not exist or is disabled; the surrounding transaction must not commit. */
export class PersonalWorkspaceUnavailableError extends Error {
  constructor() {
    super("a personal workspace cannot be created for an account that does not exist or is disabled");
    this.name = "PersonalWorkspaceUnavailableError";
  }
}

/**
 * Gives the account its personal workspace and announces `workspace.created`. Idempotent: an account that
 * already owns a workspace gets no second one and no second event, so a verification link used twice, or
 * a verification after a registration that already provisioned, leaves one workspace.
 */
export async function provisionPersonalWorkspace(
  { store, newId }: PersonalWorkspaceDependencies,
  accountId: string,
): Promise<PersonalWorkspaceOutcome> {
  const workspaceId = newId();
  const outcome = await store.create({
    accountId,
    workspaceId,
    nameSuffix: PERSONAL_WORKSPACE_NAME_SUFFIX,
    events: [{ eventId: newId(), name: "workspace.created", payload: { workspaceId, accountId } }],
    audit: ({ name, displayName }) =>
      prepareAuditRecord(
        {
          action: "workspace.created",
          workspaceId,
          actor: { type: "account", accountId, label: displayName },
          entity: { type: "workspace", id: workspaceId },
          metadata: { name },
          ipPrefix: null,
        },
        newId,
      ),
  });
  if (outcome === undefined) {
    throw new PersonalWorkspaceUnavailableError();
  }
  return outcome;
}
