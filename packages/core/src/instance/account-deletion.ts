import type { AccountDeletionGuardInput, AccountDeletionWorkspace } from "../accounts/delete.ts";
import type { DomainEvent } from "../events/catalog.ts";
import type { WorkspaceDeletionGuardResult } from "../workspaces/delete.ts";

// Deleting another account as the CE instance admin (doc 02 sections 2.10 and 11.2, doc 04 section 10.10, doc 05 sections
// 3.3 and 7.1, doc 01 section 13.2, doc 10 T1 and T18). It applies the rules of `DELETE /me` (`deleteAccount`) to the
// account named, with the ownership of its workspaces resolved first: the account must not be the only owner of a
// workspace that has other members, so the admin or the owners transfer the ownership or delete the workspace beforehand.
// Reads and writes are `sys_instance_*` system operations that check the admin again in the database and write the
// instance audit event in the same call, so this module decides what is asked and never writes an event itself.
//
// The admin's own account is not deleted here: that is `DELETE /me`, which asks for the typed address and ends the session.

/**
 * What deleting the account would do, read under the locks that keep it true for the rest of the transaction. Anything but
 * `ok` means the account is not to be deleted, and nothing was changed.
 */
export type InstanceAccountDeletionScope =
  | {
      readonly kind: "ok";
      /** Workspaces where the account is the only owner and that have other members; the account cannot be deleted while any exists. */
      readonly blocking: readonly AccountDeletionWorkspace[];
      /** Workspaces where the account is the only member; they are deleted with it. */
      readonly soleMember: readonly AccountDeletionWorkspace[];
    }
  | { readonly kind: InstanceAccountDeletionRefusal };

/** Why the account is not deleted, decided by the database. */
export type InstanceAccountDeletionRefusal =
  /** There is no such account. */
  | "unknown_account"
  /** The account is an instance admin and no other enabled account is one. */
  | "last_instance_admin"
  /** The account is the calling admin's own; `DELETE /me` deletes it. */
  | "self";

export interface InstanceAccountDeletionRequest {
  readonly accountId: string;
  /** The workspaces of `soleMember` that the guard was asked about, which go with the account. */
  readonly soleWorkspaceIds: readonly string[];
  /** A UUIDv7 generated by the caller (Q91): the identifier of the `instance.account_deleted` event. */
  readonly eventId: string;
  readonly ipPrefix: string | null;
  /** Queued in the transaction that deletes the account, and only when it does. */
  readonly events: readonly DomainEvent<"account.deleted">[];
}

/** What the database answered to the deletion; `unavailable` is a scope that no longer is what `soleWorkspaceIds` says. */
export type InstanceAccountDeletionStoreOutcome = "deleted" | "unavailable" | InstanceAccountDeletionRefusal;

/** The stores of the instance admin's account deletion, bound to the account-level transaction of the request. */
export interface InstanceAccountDeletionStore {
  /** The scope of the deletion of the account; it holds for the rest of the transaction the store is bound to. */
  scope(accountId: string): Promise<InstanceAccountDeletionScope>;
  /**
   * Deletes the account, puts `soleWorkspaceIds` through the workspace deletion path, writes the instance audit event
   * `instance.account_deleted`, and queues the jobs of the workspaces and the events, in the open transaction. Anything but
   * `deleted` writes and queues nothing.
   */
  delete(request: InstanceAccountDeletionRequest): Promise<InstanceAccountDeletionStoreOutcome>;
}

export interface InstanceAccountDeletionDependencies<Code extends string> {
  readonly store: InstanceAccountDeletionStore;
  /**
   * The deletion guard of the composition, asked with `requestedBy: 'instanceAdmin'` (doc 01 section 13.2): once for the
   * account and once for each workspace that goes with it, each naming the account that is deleted. A guard that cannot
   * answer rejects, which refuses the request before anything is written; it never refuses by throwing.
   */
  readonly guard: (input: AccountDeletionGuardInput) => Promise<WorkspaceDeletionGuardResult<Code>>;
  /** A fresh UUIDv7. */
  readonly newId: () => string;
}

export interface InstanceAccountDeletionAsk {
  /** The account to delete. */
  readonly accountId: string;
  /** The coarse network of the request, null when unknown. */
  readonly ipPrefix: string | null;
}

export type InstanceAccountDeletionOutcome<Code extends string> =
  /** The account is deleted and the request is in the instance audit stream; `workspaces` were deleted with it. */
  | { readonly kind: "deleted"; readonly workspaces: readonly AccountDeletionWorkspace[] }
  | { readonly kind: InstanceAccountDeletionRefusal }
  /** The account is the only owner of these workspaces, which have other members; nothing was written. */
  | { readonly kind: "last_owner"; readonly workspaces: readonly AccountDeletionWorkspace[] }
  /** The guard refused with `code`, for the account or for one of the workspaces; nothing was written. */
  | { readonly kind: "refused"; readonly code: Code }
  /** The workspaces changed under the request; nothing was written. */
  | { readonly kind: "unavailable" };

/**
 * Deletes the account when it is not the last instance admin or the admin's own, no workspace would be left without an owner
 * and the guard allows the account and each workspace that goes with it. The instance-admin policy and the fresh
 * re-authentication are judged before this runs, and the database checks the admin again.
 */
export async function deleteInstanceAccount<Code extends string>(
  { store, guard, newId }: InstanceAccountDeletionDependencies<Code>,
  ask: InstanceAccountDeletionAsk,
): Promise<InstanceAccountDeletionOutcome<Code>> {
  const scope = await store.scope(ask.accountId);
  if (scope.kind !== "ok") {
    return { kind: scope.kind };
  }
  if (scope.blocking.length > 0) {
    return { kind: "last_owner", workspaces: scope.blocking };
  }
  const account = await guard({ kind: "account", accountId: ask.accountId });
  if (account.outcome === "refuse") {
    return { kind: "refused", code: account.code };
  }
  for (const workspace of scope.soleMember) {
    const verdict = await guard({ kind: "workspace", accountId: ask.accountId, workspaceId: workspace.id });
    if (verdict.outcome === "refuse") {
      return { kind: "refused", code: verdict.code };
    }
  }
  const outcome = await store.delete({
    accountId: ask.accountId,
    soleWorkspaceIds: scope.soleMember.map((workspace) => workspace.id),
    eventId: newId(),
    ipPrefix: ask.ipPrefix,
    events: [{ eventId: newId(), name: "account.deleted", payload: { accountId: ask.accountId } }],
  });
  return outcome === "deleted" ? { kind: "deleted", workspaces: scope.soleMember } : { kind: outcome };
}
