import { generateCredentialToken } from "../auth/credential-tokens.ts";
import { normalizeEmail } from "../auth/email.ts";
import type { DomainEvent } from "../events/catalog.ts";
import { WORKSPACE_NAME_MAX_LENGTH } from "../workspaces/create.ts";
import type { WorkspaceDeletionGuardResult } from "../workspaces/delete.ts";
import { INVITATION_TTL_SECONDS } from "../workspaces/invitations.ts";

// The workspace operations of the CE instance admin (doc 02 section 11.1, doc 04 section 10.10, doc 05 section 3.3,
// doc 10 T1 and T18): list every workspace without any content, create a workspace for a chosen account or for the
// first owner an invitation brings, and ask for a workspace to be deleted. Each is a `sys_instance_*` system operation
// that checks the admin again in the database and writes the instance audit event in the same call, so this module
// decides what is asked and what is returned, and never writes an event itself.
//
// An owner invitation is the one invitation that carries the owner role (doc 02 section 11.1). Its token is made here
// and only its hash is stored; the value is in the outcome, for the caller to hand to the admin once, and nowhere else.

/** An owner of a workspace as the instance admin sees it. */
export interface InstanceWorkspaceOwner {
  readonly accountId: string;
  readonly displayName: string;
  readonly email: string;
}

/** A workspace of the instance list: its name, its owners and how many members it has, and no content. */
export interface InstanceWorkspace {
  readonly id: string;
  readonly name: string;
  readonly createdAt: Date;
  readonly memberCount: number;
  /** Empty while the workspace waits for the first owner an invitation will bring. */
  readonly owners: readonly InstanceWorkspaceOwner[];
}

/** How the first owner is chosen. */
export type InstanceWorkspaceOwnerSeat =
  | { readonly kind: "account"; readonly accountId: string }
  | {
      readonly kind: "invitation";
      readonly invitationId: string;
      /** The address of the first owner, normalised. */
      readonly email: string;
      /** SHA-256 of a token the caller keeps. */
      readonly tokenHash: Buffer;
      readonly ttlSeconds: number;
    };

export interface InstanceWorkspaceCreation {
  /** A UUIDv7 generated by the caller (Q91). */
  readonly workspaceId: string;
  readonly name: string;
  readonly owner: InstanceWorkspaceOwnerSeat;
  /** Announced in the transaction that creates the workspace, and only when it does; empty while the workspace has no owner. */
  readonly events: readonly DomainEvent<"workspace.created">[];
}

export type InstanceWorkspaceCreationResult =
  /** The workspace exists; `invitationExpiresAt` is the expiry of the owner invitation, null when an account was made the owner. */
  | { readonly kind: "created"; readonly invitationExpiresAt: Date | null }
  /** The chosen owner account does not exist or is disabled; nothing was written. */
  | { readonly kind: "unknown_account" };

/** The stores of the instance admin's workspace operations, bound to the account-level transaction of the request. */
export interface InstanceWorkspaceStore {
  /** Every workspace that is not being deleted, newest first, and the instance audit event `instance.workspaces_viewed`. */
  listWorkspaces(eventId: string, ipPrefix: string | null): Promise<readonly InstanceWorkspace[]>;
  /** Creates the workspace and its first owner or owner invitation, and the instance audit event `instance.workspace_created`, in one call. */
  createWorkspace(request: InstanceWorkspaceCreation, eventId: string, ipPrefix: string | null): Promise<InstanceWorkspaceCreationResult>;
  /**
   * Marks the workspace as being deleted, queues the job that removes its rows and writes the instance audit event
   * `instance.workspace_deletion_requested`, in the transaction the store is bound to. False, with nothing written and
   * nothing queued, when the workspace does not exist or is already being deleted.
   */
  markWorkspaceDeleting(workspaceId: string, eventId: string, ipPrefix: string | null): Promise<boolean>;
}

export interface InstanceWorkspaceDependencies {
  readonly store: InstanceWorkspaceStore;
  /** A fresh UUIDv7. */
  readonly newId: () => string;
}

export interface InstanceWorkspaceAsk {
  /** The coarse network of the request, null when unknown. */
  readonly ipPrefix: string | null;
}

/** The workspaces of the instance, each with its owners and member count. */
export function listInstanceWorkspaces({ store, newId }: InstanceWorkspaceDependencies, ask: InstanceWorkspaceAsk): Promise<readonly InstanceWorkspace[]> {
  return store.listWorkspaces(newId(), ask.ipPrefix);
}

export interface InstanceWorkspaceCreationAsk extends InstanceWorkspaceAsk {
  readonly name: string;
  /** Exactly one of the two is given: the request schema holds the caller to it. */
  readonly ownerAccountId?: string;
  readonly ownerEmail?: string;
  /** How long an owner invitation can be accepted for; `INVITATION_TTL_SECONDS` unless the composition says otherwise. */
  readonly ttlSeconds?: number;
}

export type InstanceWorkspaceCreationOutcome =
  | {
      readonly kind: "created";
      readonly workspaceId: string;
      /** Present when the first owner is invited: the invitation and the token whose value only this outcome holds. */
      readonly invitation?: { readonly id: string; readonly email: string; readonly expiresAt: Date; readonly token: string };
    }
  | { readonly kind: "unknown_account" };

/**
 * Creates the workspace for the account, which becomes its owner, or for the address, which receives an owner
 * invitation the workspace waits on. The workspace, its first owner or invitation and the audit event are one call of
 * the database; `workspace.created` is announced only when an account is the owner, since the event names it.
 */
export async function createInstanceWorkspace(
  { store, newId }: InstanceWorkspaceDependencies,
  ask: InstanceWorkspaceCreationAsk,
): Promise<InstanceWorkspaceCreationOutcome> {
  const length = Array.from(ask.name).length;
  if (length < 1 || length > WORKSPACE_NAME_MAX_LENGTH) {
    throw new RangeError(`a workspace name has 1 to ${String(WORKSPACE_NAME_MAX_LENGTH)} characters`);
  }
  if ((ask.ownerAccountId === undefined) === (ask.ownerEmail === undefined)) {
    throw new RangeError("a workspace is created for an owner account or an owner address, and not both");
  }
  const workspaceId = newId();
  const eventId = newId();
  if (ask.ownerAccountId !== undefined) {
    const accountId = ask.ownerAccountId;
    const result = await store.createWorkspace(
      {
        workspaceId,
        name: ask.name,
        owner: { kind: "account", accountId },
        events: [{ eventId: newId(), name: "workspace.created", payload: { workspaceId, accountId } }],
      },
      eventId,
      ask.ipPrefix,
    );
    return result.kind === "created" ? { kind: "created", workspaceId } : { kind: "unknown_account" };
  }
  const email = normalizeEmail(ask.ownerEmail ?? "");
  const token = generateCredentialToken();
  const invitationId = newId();
  const result = await store.createWorkspace(
    {
      workspaceId,
      name: ask.name,
      owner: { kind: "invitation", invitationId, email, tokenHash: token.hash, ttlSeconds: ask.ttlSeconds ?? INVITATION_TTL_SECONDS },
      events: [],
    },
    eventId,
    ask.ipPrefix,
  );
  if (result.kind !== "created" || result.invitationExpiresAt === null) {
    throw new Error("an owner invitation was requested and the store answered without one");
  }
  return { kind: "created", workspaceId, invitation: { id: invitationId, email, expiresAt: result.invitationExpiresAt, token: token.value } };
}

export interface InstanceWorkspaceDeletionDependencies<Code extends string> extends InstanceWorkspaceDependencies {
  /**
   * The deletion guard of the composition, asked with `requestedBy: 'instanceAdmin'` (doc 01 section 13.2). A guard
   * that cannot answer rejects, which refuses the request before anything is written; it never refuses by throwing.
   */
  readonly guard: (input: { readonly workspaceId: string }) => Promise<WorkspaceDeletionGuardResult<Code>>;
}

export type InstanceWorkspaceDeletionOutcome<Code extends string> =
  /** The workspace is marked, the job is queued and the request is in the instance audit stream. */
  | { readonly kind: "requested" }
  /** The guard refused with `code`; nothing was written. */
  | { readonly kind: "refused"; readonly code: Code }
  /** The workspace does not exist or is already being deleted; nothing was written. */
  | { readonly kind: "unavailable" };

/**
 * Asks the guard, then marks the workspace as being deleted and records the request in the instance audit stream. The
 * guard is the last check before the change: the instance-admin policy and the fresh re-authentication are judged
 * before the service runs.
 */
export async function requestInstanceWorkspaceDeletion<Code extends string>(
  { store, newId, guard }: InstanceWorkspaceDeletionDependencies<Code>,
  ask: InstanceWorkspaceAsk & { readonly workspaceId: string },
): Promise<InstanceWorkspaceDeletionOutcome<Code>> {
  const verdict = await guard({ workspaceId: ask.workspaceId });
  if (verdict.outcome === "refuse") {
    return { kind: "refused", code: verdict.code };
  }
  return (await store.markWorkspaceDeleting(ask.workspaceId, newId(), ask.ipPrefix)) ? { kind: "requested" } : { kind: "unavailable" };
}
