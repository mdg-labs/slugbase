import { FOLDER_COLOR_MAX, FOLDER_COLOR_MIN, FOLDER_DEFAULT_COLOR, FOLDER_DEFAULT_ICON, FOLDER_ICONS, FOLDER_NAME_MAX_LENGTH } from "@slugbase/contracts";
import type { FolderUpdateRequest, FolderUpdateResult } from "./update.ts";

// Creating a folder (doc 02 section 7.1, doc 04 section 10.7, doc 10 T2). A folder is its owner's and nobody else's: the store creates
// it for the account of the transaction and every later read, change and deletion names that owner. The name is stored as entered, with
// the whitespace around it removed, and is unique per owner without regard to case. The service checks the name before anything is
// written; a name that the owner already uses, however it is spelled, is refused by the store, which is the only place that can judge
// it under concurrent creations. The icon and the colour come from the contract's allowlist and range, which the request validation has
// applied; the service refuses a value outside them as a programming error.

/** A folder as its owner sees it. */
export interface FolderRecord {
  readonly id: string;
  /** The member who owns the folder; null once that member has left the workspace. */
  readonly ownerId: string | null;
  /** The name as the owner entered it, without surrounding whitespace. */
  readonly name: string;
  readonly icon: string;
  /** 1 to 8: the number of the `--folder-N` theme token. */
  readonly color: number;
  /** How many bookmarks are filed in the folder; plan-archived bookmarks are not counted. */
  readonly bookmarkCount: number;
  /** The `ETag` of the folder; moves by one with every change. */
  readonly version: number;
  readonly createdAt: Date;
  readonly updatedAt: Date;
  /** Who owns a folder of another member that is shared with the viewer; null for the viewer's own folder and for one whose owner has left the workspace. */
  readonly owner: FolderOwner | null;
  /** How the viewer's own folder is shared; null for a folder of another member, whose recipient sees no more than who shared it. */
  readonly shareSummary: FolderShareSummary | null;
}

/** The member who owns a folder that is shared with the viewer. */
export interface FolderOwner {
  readonly accountId: string;
  readonly displayName: string;
}

/** How a folder of the viewer's is shared: with how many members directly, and with which teams by name. A folder shared with none is private. */
export interface FolderShareSummary {
  /** The members the folder is shared with directly; the members of a team it is shared with are not counted. */
  readonly memberCount: number;
  /** The teams the folder is shared with, by name and then identifier. */
  readonly teams: readonly { readonly id: string; readonly name: string }[];
}

/** A folder of a list, with the update time as the database wrote it in text: a `Date` keeps milliseconds and the database microseconds, so the cursor of a page sorted by update time carries the text. */
export interface FolderListRow extends FolderRecord {
  readonly updatedKey: string;
}

/** What the store writes for a new folder. */
export interface NewFolder {
  /** A UUIDv7 generated by the caller (Q91). */
  readonly id: string;
  /** The member who creates it and owns it; the account of the transaction. */
  readonly ownerId: string;
  readonly name: string;
  readonly icon: string;
  readonly color: number;
}

export type FolderSort = "name" | "count" | "updated";

/** Whose folders a list covers: the viewer's own, those of other members that are shared with the viewer (directly or through a team), or both. */
export type FolderScope = "all" | "mine" | "shared";

export type FolderStoreCreationResult =
  | { readonly kind: "created"; readonly folder: FolderRecord }
  /** The owner already has a folder of that name, spelled in any case. */
  | { readonly kind: "name_taken" };

/**
 * The place after which a page resumes: the last folder of the previous page. The count is given for the sort by count and the update
 * time, as the database wrote it in text, for the sort by update time; neither for the sort by name.
 */
export interface FolderPosition {
  readonly count: number | undefined;
  readonly updated: string | undefined;
  readonly name: string;
  readonly id: string;
}

export interface FolderListRequest {
  /** The member who lists: the owner of the folders of the `mine` scope and the one the others are shared with; the account of the transaction. */
  readonly viewerId: string;
  readonly scope: FolderScope;
  /** Lists the folders whose name contains this text, without regard to case; undefined lists them all. */
  readonly search: string | undefined;
  readonly sort: FolderSort;
  /** The page starts after this place; the first page when undefined. */
  readonly after: FolderPosition | undefined;
  readonly limit: number;
}

export interface FolderStore {
  /** Inserts the folder for its owner in the workspace of the transaction. Nothing is written for `name_taken`. */
  create(folder: NewFolder): Promise<FolderStoreCreationResult>;
  /** The folder `folderId` when `viewerId` owns it in the workspace of the transaction or it is shared with `viewerId`; undefined for any other folder. */
  find(request: { readonly folderId: string; readonly viewerId: string }): Promise<FolderRecord | undefined>;
  /** The next `request.limit` folders of `request.scope` for `request.viewerId` in the workspace of the transaction with the number of bookmarks filed in each, in the order of `request.sort`, after `request.after`. */
  list(request: FolderListRequest): Promise<readonly FolderListRow[]>;
  /** How many folders of `scope` for `viewerId` in the workspace of the transaction have a name that contains `search`, but at most `limit`. */
  count(request: { readonly viewerId: string; readonly scope: FolderScope; readonly search: string | undefined; readonly limit: number }): Promise<number>;
  /** Whether the folder `folderId` is another member's and shared with `accountId` (the account of the transaction), directly or through a team: a folder it can read and may not change. */
  sharedWith(request: { readonly folderId: string; readonly accountId: string }): Promise<boolean>;
  /**
   * Applies the changes to the folder that `request.ownerId` owns. The folder is locked, and its version, read under the lock, must be one
   * of `request.expectedVersions` when that is given (`stale` otherwise). A change to the values the folder has is `unchanged` and writes
   * nothing. `name_taken` when the owner has another folder of the new name; `not_found` for a folder the owner does not own, whoever
   * does, and one that does not exist.
   */
  update(request: FolderUpdateRequest): Promise<FolderUpdateResult>;
  /** Deletes the folder that `request.ownerId` owns together with the associations of its bookmarks, which stay; false when the owner owns no such folder. */
  remove(request: { readonly folderId: string; readonly ownerId: string }): Promise<boolean>;
}

export interface FolderCreationDependencies {
  readonly store: Pick<FolderStore, "create">;
  /** Generates the identifier of a new folder: a UUIDv7. */
  readonly newId: () => string;
}

export interface FolderCreationAsk {
  /** The member who creates the folder. */
  readonly accountId: string;
  readonly name: string;
  /** Left out: `folder`. */
  readonly icon: string | undefined;
  /** Left out: 1. */
  readonly color: number | undefined;
}

export type FolderCreationOutcome =
  | { readonly kind: "created"; readonly folder: FolderRecord }
  | { readonly kind: "invalid_name"; readonly reason: FolderNameRefusal }
  | { readonly kind: "name_taken" };

export type FolderNameRefusal = "empty" | "too_long";

/** The name as it is stored, or the reason it is refused: empty, or longer than 64 characters, once the whitespace around it is removed. */
export function normalizeFolderName(name: string): { readonly name: string } | { readonly refusal: FolderNameRefusal } {
  const trimmed = name.trim();
  // Characters as the database counts them (`length()` counts code points), so a surrogate pair is one.
  const length = trimmed.replace(/[\uD800-\uDBFF][\uDC00-\uDFFF]/g, "_").length;
  if (length < 1) {
    return { refusal: "empty" };
  }
  return length > FOLDER_NAME_MAX_LENGTH ? { refusal: "too_long" } : { name: trimmed };
}

/** Throws for an icon outside the allowlist or a colour outside 1 to 8: the request validation refuses both before a service is called. */
export function assertFolderStyle(style: { readonly icon?: string | undefined; readonly color?: number | undefined }): void {
  if (style.icon !== undefined && !(FOLDER_ICONS as readonly string[]).includes(style.icon)) {
    throw new RangeError("a folder icon is one of the published list");
  }
  if (style.color !== undefined && (!Number.isInteger(style.color) || style.color < FOLDER_COLOR_MIN || style.color > FOLDER_COLOR_MAX)) {
    throw new RangeError(`a folder colour is ${String(FOLDER_COLOR_MIN)} to ${String(FOLDER_COLOR_MAX)}`);
  }
}

export async function createFolder({ store, newId }: FolderCreationDependencies, ask: FolderCreationAsk): Promise<FolderCreationOutcome> {
  const normalized = normalizeFolderName(ask.name);
  if ("refusal" in normalized) {
    return { kind: "invalid_name", reason: normalized.refusal };
  }
  assertFolderStyle(ask);
  return store.create({
    id: newId(),
    ownerId: ask.accountId.toLowerCase(),
    name: normalized.name,
    icon: ask.icon ?? FOLDER_DEFAULT_ICON,
    color: ask.color ?? FOLDER_DEFAULT_COLOR,
  });
}
