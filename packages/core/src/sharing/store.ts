import type { SHARE_TARGET_KINDS } from "@slugbase/contracts";

// Sharing in a workspace (doc 02 section 8, doc 05 section 2.5, doc 10 T1, T2 and T11). A share gives a member or a team of the workspace read
// access to what its owner shares; sharing never crosses a workspace, and only the owner of a bookmark grants, lists or revokes its shares. Which
// entitlement a request needs follows the target (`sharing.members` for a member, `sharing.teams` for a team) and is decided by the server before a
// service runs. A second kind of shared object (a folder) joins the target types below; the stores of the objects are separate.

/** The kinds of target a share names: one member of the workspace, or one of its teams. */
export type ShareTargetKind = (typeof SHARE_TARGET_KINDS)[number];

/** The entitlement that lets a workspace share with a target of each kind (doc 01 section 7.5). */
export const SHARE_ENTITLEMENTS = { member: "sharing.members", team: "sharing.teams" } as const satisfies Readonly<Record<ShareTargetKind, string>>;

/** Whom a share is granted to. */
export type ShareTarget =
  | { readonly kind: "member"; readonly accountId: string }
  | { readonly kind: "team"; readonly teamId: string };

/** A member or a team the caller can share with. A member is shown under the co-member projection of its account (doc 05 section 2.1). */
export interface ShareTargetRecord {
  readonly kind: ShareTargetKind;
  /** The account identifier of a member, the team identifier of a team. */
  readonly id: string;
  /** The display name of a member, the name of a team. */
  readonly name: string;
  /** The address of a member; null for a team. */
  readonly email: string | null;
}

export interface ShareTargetSearch {
  /** A part of a name or, for a member, of an address, without regard to case; undefined lists everything. */
  readonly q: string | undefined;
  /** The caller, who is never offered as a target. */
  readonly excludeAccountId: string;
  /** The kinds the workspace holds the entitlement for; the others are not searched. */
  readonly kinds: readonly ShareTargetKind[];
  readonly limit: number;
}

export interface ShareTargetStore {
  /** The members (other than `excludeAccountId`) and the teams of the workspace of the transaction that match, in the order of name then identifier, at most `limit`. */
  search(request: ShareTargetSearch): Promise<readonly ShareTargetRecord[]>;
}

/** A grant on a bookmark, with the name of its target as it is now. Exactly one of `accountId` and `teamId` is set. */
export interface BookmarkShareRecord {
  readonly id: string;
  readonly bookmarkId: string;
  readonly accountId: string | null;
  readonly teamId: string | null;
  readonly name: string;
  readonly email: string | null;
  readonly createdAt: Date;
}

export interface BookmarkShareList {
  readonly shares: readonly BookmarkShareRecord[];
  /** The distinct members other than the owner who can read the bookmark through its shares: the members it is shared with and the members of the teams it is shared with. */
  readonly audienceSize: number;
}

export interface NewBookmarkShare {
  /** A UUIDv7 generated by the caller (Q91). */
  readonly id: string;
  readonly bookmarkId: string;
  /** The account that grants; the owner of the bookmark. */
  readonly grantedBy: string;
  readonly target: ShareTarget;
}

export type BookmarkShareGrant =
  | { readonly kind: "granted"; readonly share: BookmarkShareRecord }
  /** The bookmark is shared with the target already; `share` is that share and nothing was written. */
  | { readonly kind: "existing"; readonly share: BookmarkShareRecord }
  /** The target is no member of the workspace, or no team of it; nothing was written. */
  | { readonly kind: "unknown_target" };

/** What the caller wants to do with the shares of a bookmark: a grant needs a bookmark that is not plan-archived. */
export type BookmarkShareUse = "read" | "grant" | "revoke";

export interface BookmarkShareStore {
  /**
   * Whether the workspace of the transaction has the bookmark `bookmarkId` and `ownerId` owns it. For a `grant` the bookmark is also locked against
   * its deletion for the rest of the transaction, and a bookmark that is plan-archived is refused: its shares can still be read and ended.
   */
  ownedBookmark(request: { readonly bookmarkId: string; readonly ownerId: string; readonly use: BookmarkShareUse }): Promise<boolean>;
  /** The shares of the bookmark, in the order of their creation, and the size of the audience they make. */
  list(bookmarkId: string): Promise<BookmarkShareList>;
  /**
   * Shares the bookmark with the target. The target is locked against its removal from the workspace (or its deletion) for the rest of the
   * transaction, so a share is never left naming a target that is gone. A repeat returns the share that exists.
   */
  grant(request: NewBookmarkShare): Promise<BookmarkShareGrant>;
  /** Deletes the share `shareId` of the bookmark and answers it as it was; undefined when the bookmark has no such share. */
  revoke(request: { readonly bookmarkId: string; readonly shareId: string }): Promise<BookmarkShareRecord | undefined>;
}
