import { normalizeTagName } from "../tags/create.ts";

// The tags a creation or a change of a bookmark names (doc 02 sections 5.1 and 7.2, doc 04 section 10.6, doc 13 Q22, doc 10 T2). A tag is named by
// its identifier or by its name, and a name that the owner has no tag of yet creates one in the transaction that tags the bookmark. Only the owner
// of a bookmark tags it, and only with the owner's own tags: the store finds every identifier by owner, so another member's tag, one of another
// workspace and one that does not exist are the same `tag_not_found`.

/** A tag named by its name: the owner's tag of that name (whatever its case), or a new tag with `newId` when the owner has none. */
export interface BookmarkTagName {
  /** The name as it is stored: the whitespace around it removed, 1 to 40 characters. */
  readonly name: string;
  /** A UUIDv7 generated by the caller (Q91), used only when the tag is created. */
  readonly newId: string;
}

/** The tags a bookmark is to carry: the union of the tags named by identifier and by name. */
export interface BookmarkTagSelection {
  /** The owner's tags by identifier, lower-cased and without repeats. */
  readonly ids: readonly string[];
  /** The tags by name, one for each name once its case is disregarded. */
  readonly names: readonly BookmarkTagName[];
}

/** A tag a bookmark carries, as the bookmark shows it. */
export interface BookmarkTagRef {
  readonly id: string;
  readonly name: string;
}

/** The selection of the identifiers and names a request sent, or undefined when it sent neither; a name outside 1 to 40 characters is a `RangeError`, since the contract refuses it first. */
export function bookmarkTagSelection(
  tagIds: readonly string[] | undefined,
  tagNames: readonly string[] | undefined,
  newId: () => string,
): BookmarkTagSelection | undefined {
  if (tagIds === undefined && tagNames === undefined) {
    return undefined;
  }
  const names = new Map<string, BookmarkTagName>();
  for (const given of tagNames ?? []) {
    const normalized = normalizeTagName(given);
    if ("refusal" in normalized) {
      throw new RangeError("a tag name has 1 to 40 characters");
    }
    const key = normalized.name.toLowerCase();
    if (!names.has(key)) {
      names.set(key, { name: normalized.name, newId: newId() });
    }
  }
  return { ids: [...new Set((tagIds ?? []).map((id) => id.toLowerCase()))], names: [...names.values()] };
}
