import type { EntitlementLimit } from "../entitlements/catalog.ts";
import type { DomainEvent } from "../events/catalog.ts";
import { parseSlug } from "../go/slug.ts";
import { bookmarkTagSelection, type BookmarkTagRef, type BookmarkTagSelection } from "./tagging.ts";
import type { BookmarkUpdateRequest, BookmarkUpdateResult } from "./update.ts";
import { normalizeBookmarkUrl, type BookmarkUrlRefusal } from "./url.ts";

// Creating a bookmark (doc 02 sections 5.1 and 5.2, doc 04 section 10.6, doc 01 section 7.5, doc 10 T1, T11, T12 and
// T13). The service validates and normalises everything the caller sent before anything is written, then asks the store
// to take one place under `bookmarks.max`, insert the row for the account that asked and queue the events, all in the
// transaction the store is bound to. The count the ceiling is compared with is the workspace's `bookmark_count`, which
// the store reads under the workspace's row lock and raises in the same transaction as the insert, so two creations
// that run in parallel at the limit minus one make one. A refusal writes nothing; a failure of any write rejects, so the
// caller's transaction must not commit.

/** The longest bookmark title, in characters (doc 02 section 5.1). */
export const BOOKMARK_TITLE_MAX_LENGTH = 300;

/** The longest bookmark description, in characters (doc 02 section 5.1). */
export const BOOKMARK_DESCRIPTION_MAX_LENGTH = 1000;

/** A folder a bookmark is filed in, as the bookmark shows it. */
export interface BookmarkFolderRef {
  readonly id: string;
  readonly name: string;
  readonly icon: string;
  /** 1 to 8: the number of the `--folder-N` theme token. */
  readonly color: number;
}

/** The ways a bookmark of another member is shared with the caller: with them, with a team they are in, or through a shared folder it is filed in. */
export const BOOKMARK_SHARED_VIA = ["direct", "team", "folder"] as const;

export type BookmarkSharedVia = (typeof BOOKMARK_SHARED_VIA)[number];

/** The member who owns a bookmark that is shared with the caller, as a member of the workspace sees them. */
export interface BookmarkOwner {
  readonly accountId: string;
  readonly displayName: string;
}

/** A bookmark as the member who reads it sees it: the owner's own, or one shared with them, which carries nothing of the owner's folders, tags or pin. */
export interface BookmarkRecord {
  readonly id: string;
  /** The member who owns it; null once that member has left the workspace (doc 02 section 3.5). */
  readonly ownerId: string | null;
  readonly url: string;
  readonly host: string;
  readonly title: string;
  readonly description: string | null;
  readonly slug: string | null;
  readonly forwarding: boolean;
  /** Whether the reader pinned it: always false for a bookmark shared with them, since a pin is the owner's (Q22). */
  readonly pinned: boolean;
  readonly openCount: number;
  readonly lastOpenedAt: Date | null;
  /** Who owns it when it is shared with the reader; null for the reader's own bookmark and for one whose owner has left the workspace. */
  readonly owner: BookmarkOwner | null;
  /** How it is shared with the reader; null for the reader's own bookmark. */
  readonly sharedVia: BookmarkSharedVia | null;
  /** The reader's folders the bookmark is filed in, in the order of their names; none for a bookmark shared with them. Filing does not move `version`. */
  readonly folders: readonly BookmarkFolderRef[];
  /** The caller's own tags on the bookmark, in the order of their names; another member's tags are never in it. Tagging does not move `version`. */
  readonly tags: readonly BookmarkTagRef[];
  /** The `ETag` of the bookmark. */
  readonly version: number;
  readonly createdAt: Date;
  readonly updatedAt: Date;
}

/** What the store writes for a new bookmark. */
export interface NewBookmark {
  /** A UUIDv7 generated by the caller (Q91). */
  readonly id: string;
  /** The member who creates it and owns it; the account of the transaction. */
  readonly ownerId: string;
  readonly url: string;
  readonly urlCanonical: string;
  readonly host: string;
  readonly title: string;
  readonly description: string | null;
  readonly pinned: boolean;
  /** The slug in its normal form, already in the grammar; left out for none. */
  readonly slug?: string;
  /** Whether /go forwards to the bookmark: never true without a slug, and false when left out. */
  readonly forwarding?: boolean;
}

export interface BookmarkCreationRequest {
  readonly bookmark: NewBookmark;
  /** The workspace's `bookmarks.max`, which the store judges against the count it reads under the workspace's row lock. */
  readonly ceiling: EntitlementLimit;
  /** Announced in the transaction that creates the bookmark, and only when it does. */
  readonly events: readonly DomainEvent<"bookmark.created">[];
  /** The owner's folders the new bookmark is filed in, without repeats; empty for none. */
  readonly folderIds: readonly string[];
  /** The owner's tags the new bookmark carries; none for an empty selection. */
  readonly tags: BookmarkTagSelection;
}

export type BookmarkStoreResult =
  | { readonly kind: "created"; readonly bookmark: BookmarkRecord }
  /** The workspace already holds `used` bookmarks, which is as many as the ceiling allows. */
  | { readonly kind: "limit_reached"; readonly used: number }
  /** The workspace of the transaction cannot be reached: it does not exist, is being deleted, or the account is no member. */
  | { readonly kind: "unavailable" }
  /** One of the folders is not one the owner has in this workspace; nothing is written. */
  | { readonly kind: "folder_not_found" }
  /** One of the tags is not one the owner has in this workspace; nothing is written. */
  | { readonly kind: "tag_not_found" }
  /** The owner already has another bookmark with the slug in this workspace; nothing is written. */
  | { readonly kind: "slug_taken" };

export interface BookmarkStore {
  /**
   * Takes one place under `ceiling` from the workspace's bookmark count, inserts the bookmark and queues the events, in
   * the transaction the store is bound to. The count is read under the workspace's row lock and raised in the same
   * transaction as the insert; nothing is written for `limit_reached`, `unavailable`, `folder_not_found`, `tag_not_found` and `slug_taken` (a slug the owner has on another bookmark, found
   * before the first write; two creations that set one slug at once meet at the table's key, and the loser's statement throws the error `isBookmarkSlugTaken` of `@slugbase/db` tells, which ends its transaction). The bookmark is filed in the
   * folders of `request.folderIds` and tagged in the same transaction, and only with folders and tags its owner owns; a name of `request.tags` the
   * owner has no tag of creates one in that transaction.
   */
  create(request: BookmarkCreationRequest): Promise<BookmarkStoreResult>;
  /**
   * The bookmark of the workspace of the transaction with that identifier, when the account of the transaction can read it: it owns it, or it is shared with the account
   * directly, through a team or through a folder. Undefined when there is none, when it is plan-archived and when the account cannot read it. A bookmark shared with the
   * account comes with its owner and how it is shared (`owner`, `sharedVia`), and with none of the owner's folders or tags and not the owner's pin.
   */
  find(bookmarkId: string): Promise<BookmarkRecord | undefined>;
  /**
   * Whether the bookmark is shared with `accountId` (the account of the transaction): the account can read it through a share, directly, through a team or through
   * a folder, and someone else owns it. A plan-archived bookmark is not. It tells a bookmark the account may read and not change (forbidden) from one it cannot see (not found).
   */
  sharedWith(request: { readonly bookmarkId: string; readonly accountId: string }): Promise<boolean>;
  /**
   * Changes the bookmark of the workspace of the transaction that `request.ownerId` owns and that is not plan-archived, under the
   * row's lock: a version outside `request.expectedVersions` is `stale`, a patch that names the values the bookmark has is
   * `unchanged`, and the rest is written and moves the version by one. Nothing is written for `stale`, `unchanged` and `not_found`.
   */
  update(request: BookmarkUpdateRequest): Promise<BookmarkUpdateResult>;
  /**
   * Deletes the bookmark of the workspace of the transaction that `request.ownerId` owns, a plan-archived one included, and gives
   * its place under `bookmarks.max` back unless it was archived. False, with nothing written, when there is no such bookmark.
   */
  remove(request: { readonly bookmarkId: string; readonly ownerId: string }): Promise<boolean>;
}

export interface BookmarkCreationDependencies {
  readonly store: Pick<BookmarkStore, "create">;
  /** A fresh UUIDv7. */
  readonly newId: () => string;
}

export interface BookmarkCreationAsk {
  readonly workspaceId: string;
  /** The member who creates the bookmark and owns it. */
  readonly accountId: string;
  readonly url: string;
  readonly title: string;
  readonly description: string | undefined;
  readonly pinned: boolean | undefined;
  /** The slug as the caller wrote it; it is trimmed and lower-cased, then held to the grammar. None when left out. */
  readonly slug?: string | undefined;
  /** Whether /go forwards to the bookmark. It needs a slug; when left out it is true if a slug is given and false otherwise. */
  readonly forwarding?: boolean | undefined;
  /** The folders to file the bookmark in; none when left out. */
  readonly folderIds: readonly string[] | undefined;
  /** The owner's tags to put on the bookmark by identifier, and by name (a name the owner has no tag of creates one); none when left out. Both together name the union. */
  readonly tagIds?: readonly string[] | undefined;
  readonly tagNames?: readonly string[] | undefined;
  /** The workspace's `bookmarks.max`. */
  readonly ceiling: EntitlementLimit;
}

export type BookmarkCreationOutcome =
  | { readonly kind: "created"; readonly bookmark: BookmarkRecord }
  /** The URL is refused; nothing was written. */
  | { readonly kind: "url_refused"; readonly reason: BookmarkUrlRefusal }
  /** The workspace holds `used` bookmarks, as many as `limit` allows; nothing was written. */
  | { readonly kind: "limit_reached"; readonly limit: number; readonly used: number }
  /** The workspace cannot be reached; nothing was written. */
  | { readonly kind: "unavailable" }
  /** A folder is not one the account has in this workspace (another member's, another workspace's, or none); nothing was written. */
  | { readonly kind: "folder_not_found" }
  /** A tag is not one the account has in this workspace (another member's, another workspace's, or none); nothing was written. */
  | { readonly kind: "tag_not_found" }
  /** The slug is outside the grammar once trimmed and lower-cased; nothing was written. */
  | { readonly kind: "slug_invalid" }
  /** Forwarding was asked for without a slug; nothing was written. */
  | { readonly kind: "forwarding_requires_slug" }
  /** The account already has another bookmark with the slug in this workspace; nothing was written. */
  | { readonly kind: "slug_taken" };

function checkLength(field: string, value: string, min: number, max: number): void {
  const length = Array.from(value).length;
  if (length < min || length > max) {
    throw new RangeError(`a bookmark ${field} has ${String(min)} to ${String(max)} characters`);
  }
}

/**
 * Creates the bookmark for `ask.accountId` in the workspace of the transaction and announces `bookmark.created`. The
 * title and the description are the trimmed values the contract passes on; an empty description is stored as none. A slug is
 * trimmed and lower-cased and then held to the grammar before anything is written, and forwarding is true when a slug is given and
 * the caller says nothing else.
 */
export async function createBookmark({ store, newId }: BookmarkCreationDependencies, ask: BookmarkCreationAsk): Promise<BookmarkCreationOutcome> {
  const normalized = normalizeBookmarkUrl(ask.url);
  if (!normalized.ok) {
    return { kind: "url_refused", reason: normalized.reason };
  }
  checkLength("title", ask.title, 1, BOOKMARK_TITLE_MAX_LENGTH);
  const description = ask.description === undefined || ask.description === "" ? null : ask.description;
  if (description !== null) {
    checkLength("description", description, 1, BOOKMARK_DESCRIPTION_MAX_LENGTH);
  }

  let slug: string | null = null;
  if (ask.slug !== undefined) {
    const parsed = parseSlug(ask.slug);
    if (parsed === undefined) {
      return { kind: "slug_invalid" };
    }
    slug = parsed;
  }
  if (ask.forwarding === true && slug === null) {
    return { kind: "forwarding_requires_slug" };
  }

  const id = newId();
  const result = await store.create({
    bookmark: {
      id,
      ownerId: ask.accountId,
      url: normalized.value.url,
      urlCanonical: normalized.value.canonical,
      host: normalized.value.host,
      title: ask.title,
      description,
      pinned: ask.pinned ?? false,
      ...(slug === null ? {} : { slug, forwarding: ask.forwarding ?? true }),
    },
    ceiling: ask.ceiling,
    folderIds: [...new Set((ask.folderIds ?? []).map((id) => id.toLowerCase()))],
    tags: bookmarkTagSelection(ask.tagIds, ask.tagNames, newId) ?? { ids: [], names: [] },
    events: [{ eventId: newId(), name: "bookmark.created", payload: { workspaceId: ask.workspaceId, bookmarkId: id, accountId: ask.accountId } }],
  });
  if (result.kind === "limit_reached") {
    if (ask.ceiling === "unlimited") {
      throw new Error("the store refused a bookmark under an unlimited ceiling");
    }
    return { kind: "limit_reached", limit: ask.ceiling, used: result.used };
  }
  return result;
}
