import type { EntitlementLimit } from "../entitlements/catalog.ts";
import type { DomainEvent } from "../events/catalog.ts";
import { normalizeBookmarkUrl, type BookmarkUrlRefusal } from "./url.ts";

// Creating a bookmark (doc 02 sections 5.1 and 5.2, doc 04 section 10.6, doc 01 section 7.5, doc 10 T1, T11, T12 and
// T13). The service validates and normalises everything the caller sent before anything is written, then asks the store
// to take one place under `bookmarks.max`, insert the row for the account that asked and queue the events, all in the
// transaction the store is bound to. The count the ceiling is compared with is the workspace's `bookmark_count`, which
// the store reads under the workspace's row lock and raises in the same transaction as the insert, so two creations
// that run in parallel at the limit minus one make one. A refusal writes nothing; a failure of any write rejects, so the
// caller's transaction must not commit.

/** The longest bookmark title, in characters (doc 02 section 5.1). */
export const BOOKMARK_TITLE_MAX_LENGTH = 300;

/** The longest bookmark description, in characters (doc 02 section 5.1). */
export const BOOKMARK_DESCRIPTION_MAX_LENGTH = 1000;

/** A bookmark as its owner sees it. */
export interface BookmarkRecord {
  readonly id: string;
  /** The member who owns it; null once that member has left the workspace (doc 02 section 3.5). */
  readonly ownerId: string | null;
  readonly url: string;
  readonly host: string;
  readonly title: string;
  readonly description: string | null;
  readonly slug: string | null;
  readonly forwarding: boolean;
  readonly pinned: boolean;
  readonly openCount: number;
  readonly lastOpenedAt: Date | null;
  /** The `ETag` of the bookmark. */
  readonly version: number;
  readonly createdAt: Date;
  readonly updatedAt: Date;
}

/** What the store writes for a new bookmark. */
export interface NewBookmark {
  /** A UUIDv7 generated by the caller (Q91). */
  readonly id: string;
  /** The member who creates it and owns it; the account of the transaction. */
  readonly ownerId: string;
  readonly url: string;
  readonly urlCanonical: string;
  readonly host: string;
  readonly title: string;
  readonly description: string | null;
  readonly pinned: boolean;
}

export interface BookmarkCreationRequest {
  readonly bookmark: NewBookmark;
  /** The workspace's `bookmarks.max`, which the store judges against the count it reads under the workspace's row lock. */
  readonly ceiling: EntitlementLimit;
  /** Announced in the transaction that creates the bookmark, and only when it does. */
  readonly events: readonly DomainEvent<"bookmark.created">[];
}

export type BookmarkStoreResult =
  | { readonly kind: "created"; readonly bookmark: BookmarkRecord }
  /** The workspace already holds `used` bookmarks, which is as many as the ceiling allows. */
  | { readonly kind: "limit_reached"; readonly used: number }
  /** The workspace of the transaction cannot be reached: it does not exist, is being deleted, or the account is no member. */
  | { readonly kind: "unavailable" };

export interface BookmarkStore {
  /**
   * Takes one place under `ceiling` from the workspace's bookmark count, inserts the bookmark and queues the events, in
   * the transaction the store is bound to. The count is read under the workspace's row lock and raised in the same
   * transaction as the insert; nothing is written for `limit_reached` and `unavailable`.
   */
  create(request: BookmarkCreationRequest): Promise<BookmarkStoreResult>;
  /** The bookmark of the workspace of the transaction with that identifier, whoever owns it; undefined when there is none. */
  find(bookmarkId: string): Promise<BookmarkRecord | undefined>;
}

export interface BookmarkCreationDependencies {
  readonly store: Pick<BookmarkStore, "create">;
  /** A fresh UUIDv7. */
  readonly newId: () => string;
}

export interface BookmarkCreationAsk {
  readonly workspaceId: string;
  /** The member who creates the bookmark and owns it. */
  readonly accountId: string;
  readonly url: string;
  readonly title: string;
  readonly description: string | undefined;
  readonly pinned: boolean | undefined;
  /** The workspace's `bookmarks.max`. */
  readonly ceiling: EntitlementLimit;
}

export type BookmarkCreationOutcome =
  | { readonly kind: "created"; readonly bookmark: BookmarkRecord }
  /** The URL is refused; nothing was written. */
  | { readonly kind: "url_refused"; readonly reason: BookmarkUrlRefusal }
  /** The workspace holds `used` bookmarks, as many as `limit` allows; nothing was written. */
  | { readonly kind: "limit_reached"; readonly limit: number; readonly used: number }
  /** The workspace cannot be reached; nothing was written. */
  | { readonly kind: "unavailable" };

function checkLength(field: string, value: string, min: number, max: number): void {
  const length = Array.from(value).length;
  if (length < min || length > max) {
    throw new RangeError(`a bookmark ${field} has ${String(min)} to ${String(max)} characters`);
  }
}

/**
 * Creates the bookmark for `ask.accountId` in the workspace of the transaction and announces `bookmark.created`. The
 * title and the description are the trimmed values the contract passes on; an empty description is stored as none.
 */
export async function createBookmark({ store, newId }: BookmarkCreationDependencies, ask: BookmarkCreationAsk): Promise<BookmarkCreationOutcome> {
  const normalized = normalizeBookmarkUrl(ask.url);
  if (!normalized.ok) {
    return { kind: "url_refused", reason: normalized.reason };
  }
  checkLength("title", ask.title, 1, BOOKMARK_TITLE_MAX_LENGTH);
  const description = ask.description === undefined || ask.description === "" ? null : ask.description;
  if (description !== null) {
    checkLength("description", description, 1, BOOKMARK_DESCRIPTION_MAX_LENGTH);
  }

  const id = newId();
  const result = await store.create({
    bookmark: {
      id,
      ownerId: ask.accountId,
      url: normalized.value.url,
      urlCanonical: normalized.value.canonical,
      host: normalized.value.host,
      title: ask.title,
      description,
      pinned: ask.pinned ?? false,
    },
    ceiling: ask.ceiling,
    events: [{ eventId: newId(), name: "bookmark.created", payload: { workspaceId: ask.workspaceId, bookmarkId: id, accountId: ask.accountId } }],
  });
  if (result.kind === "limit_reached") {
    if (ask.ceiling === "unlimited") {
      throw new Error("the store refused a bookmark under an unlimited ceiling");
    }
    return { kind: "limit_reached", limit: ask.ceiling, used: result.used };
  }
  return result;
}
