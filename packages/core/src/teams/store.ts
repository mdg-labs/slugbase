import { TEAM_DESCRIPTION_MAX_LENGTH, TEAM_NAME_MAX_LENGTH } from "@slugbase/contracts";

// The teams of a workspace (doc 02 section 4, doc 05 section 2.3, doc 10 T1, T2 and T11). A team is the workspace's and no member's: every
// member reads the teams and their members (the share picker lists them), and an admin or owner, with the `teams.manage` entitlement, changes
// them; the server decides both before a service runs. The name is stored as entered, with the whitespace around it removed, and is unique per
// workspace without regard to case. The services validate what the caller sent before anything is written; a name that is taken however it is
// spelled is refused by the store, the only place that can judge it under concurrent requests.

/** A team of a list: the team and how many members it has. */
export interface TeamRecord {
  readonly id: string;
  /** The name as it was entered, without surrounding whitespace. */
  readonly name: string;
  readonly description: string;
  readonly memberCount: number;
  /** The `ETag` of the team; moves by one with every change of the name or the description. */
  readonly version: number;
  readonly createdAt: Date;
  readonly updatedAt: Date;
}

/** A member of a team, as the co-member projection of its account shows it (doc 05 section 2.1). */
export interface TeamMemberRecord {
  readonly accountId: string;
  readonly displayName: string;
  readonly email: string;
}

/** A team with its members, ordered by display name and then account. */
export interface TeamDetail extends TeamRecord {
  readonly members: readonly TeamMemberRecord[];
}

/** What the store writes for a new team. */
export interface NewTeam {
  /** A UUIDv7 generated by the caller (Q91). */
  readonly id: string;
  readonly name: string;
  readonly description: string;
}

export type TeamStoreCreationResult =
  | { readonly kind: "created"; readonly team: TeamDetail }
  /** The workspace already has a team of that name, spelled in any case. */
  | { readonly kind: "name_taken" };

/** The place after which a page resumes: the last team of the previous page. */
export interface TeamPosition {
  readonly name: string;
  readonly id: string;
}

export interface TeamListRequest {
  /** The page starts after this place; the first page when undefined. */
  readonly after: TeamPosition | undefined;
  readonly limit: number;
}

export interface TeamChanges {
  readonly name?: string;
  readonly description?: string;
}

export interface TeamUpdateRequest {
  readonly teamId: string;
  readonly changes: TeamChanges;
  /** The versions the caller accepts (its `If-Match`); undefined when it makes no precondition. An empty list matches none. */
  readonly expectedVersions: readonly number[] | undefined;
}

export type TeamUpdateResult =
  /** The team was changed; `team` is the row after the change and `previousName` the name it had. */
  | { readonly kind: "updated"; readonly team: TeamDetail; readonly previousName: string }
  /** The patch names the values the team already has; nothing was written and the version stays. */
  | { readonly kind: "unchanged"; readonly team: TeamDetail }
  /** The version of the team, read under its lock, is none of the accepted ones; nothing was written. */
  | { readonly kind: "stale" }
  /** The workspace has another team of that name; nothing was written. */
  | { readonly kind: "name_taken" }
  | { readonly kind: "not_found" };

export type TeamMembersReplacement =
  /** The set was replaced; `team` has the new members, and `added` and `removed` count the memberships written and deleted. */
  | { readonly kind: "replaced"; readonly team: TeamDetail; readonly added: number; readonly removed: number }
  /** The team has exactly these members already; nothing was written. */
  | { readonly kind: "unchanged"; readonly team: TeamDetail }
  /** An account of the set is no member of the workspace; nothing was written. */
  | { readonly kind: "unknown_members" }
  | { readonly kind: "not_found" };

export interface TeamStore {
  /** Inserts the team in the workspace of the transaction, with no members. Nothing is written for `name_taken`. */
  create(team: NewTeam): Promise<TeamStoreCreationResult>;
  /** The next `request.limit` teams of the workspace of the transaction in the order of name and then identifier, after `request.after`. */
  list(request: TeamListRequest): Promise<readonly TeamRecord[]>;
  /** The team `teamId` with its members when the workspace of the transaction has it; undefined for any other team. */
  find(teamId: string): Promise<TeamDetail | undefined>;
  /**
   * Applies the changes to the team. The team is locked, and its version, read under the lock, must be one of `request.expectedVersions` when
   * that is given (`stale` otherwise). A change to the values the team has is `unchanged` and writes nothing.
   */
  update(request: TeamUpdateRequest): Promise<TeamUpdateResult>;
  /** Deletes the team together with its memberships and answers the name it had; undefined when the workspace has no such team. */
  remove(teamId: string): Promise<string | undefined>;
  /**
   * Makes `accountIds` the members of the team. The team is locked, and every account must be a current member of the workspace, which is locked
   * for the rest of the transaction so a member who leaves meanwhile is neither added nor left in the team.
   */
  replaceMembers(request: { readonly teamId: string; readonly accountIds: readonly string[] }): Promise<TeamMembersReplacement>;
}

export type TeamTextRefusal = "empty" | "too_long";

/** Characters as the database counts them (`length()` counts code points), so a surrogate pair is one. */
function lengthOf(text: string): number {
  return text.replace(/[\uD800-\uDBFF][\uDC00-\uDFFF]/g, "_").length;
}

/** The name as it is stored, or the reason it is refused: empty, or longer than 64 characters, once the whitespace around it is removed. */
export function normalizeTeamName(name: string): { readonly name: string } | { readonly refusal: TeamTextRefusal } {
  const trimmed = name.trim();
  const length = lengthOf(trimmed);
  if (length < 1) {
    return { refusal: "empty" };
  }
  return length > TEAM_NAME_MAX_LENGTH ? { refusal: "too_long" } : { name: trimmed };
}

/** The description as it is stored, or `too_long` when it has more than 280 characters once the whitespace around it is removed. An empty one is allowed. */
export function normalizeTeamDescription(description: string): { readonly description: string } | { readonly refusal: "too_long" } {
  const trimmed = description.trim();
  return lengthOf(trimmed) > TEAM_DESCRIPTION_MAX_LENGTH ? { refusal: "too_long" } : { description: trimmed };
}

/** What a service says about a name or a description it refuses. */
export interface TeamInvalid {
  readonly kind: "invalid";
  readonly field: "name" | "description";
  readonly reason: TeamTextRefusal;
}
