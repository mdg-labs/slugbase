import type { DomainEvent } from "../events/catalog.ts";
import type { AccountDeletionScope, AccountDeletionWorkspace } from "./delete.ts";

// The access mode of an account (doc 02 sections 2.11 and 11.2, doc 01 section 13.6, doc 05 sections 2.1 and 3.3, doc 10 T4 and
// T18): `full`, `exportOnly` or `disabled`. In `exportOnly` the account can sign in, read what it can see and run the exports, and
// the HTTP chain refuses everything else (`403 account_export_only`); at the end date its end action disables or deletes it. The
// mode is set by an instance admin (`setInstanceAccountAccessMode`) or, from a composed deployment's own job, by the exported
// service `setAccountAccessMode` below, and ended by the daily maintenance job (`endAccessMode`). Both write their audit event in
// the same call as the change, through a named system operation of the database, so this module decides what is asked and never
// writes an event itself.

/** The three modes of an account. `disabled` is the disabled state (`disabled_at`) and is never set by `setAccountAccessMode`. */
export const ACCOUNT_ACCESS_MODES = ["full", "exportOnly", "disabled"] as const;

export type AccountAccessMode = (typeof ACCOUNT_ACCESS_MODES)[number];

/** What happens when an export-only period ends. */
export const EXPORT_ONLY_END_ACTIONS = ["disable", "delete"] as const;

export type ExportOnlyEndAction = (typeof EXPORT_ONLY_END_ACTIONS)[number];

/** A mode that can be set: `disabled` has its own operation. `full` carries neither date nor action; `exportOnly` carries both. */
export type AccessModeChange =
  | { readonly mode: "full" }
  | { readonly mode: "exportOnly"; readonly until: Date; readonly endAction: ExportOnlyEndAction };

/**
 * What the database answered to a change of the mode. Anything but `set` and `cleared` changed nothing and wrote nothing.
 */
export type AccessModeOutcome =
  /** The account is export-only now, with the end date and end action asked for. */
  | "set"
  /** The account is `full` again. */
  | "cleared"
  /** The account was in the state asked for already. */
  | "unchanged"
  /** There is no such account; for the exported service, also an account other than the one of the transaction. */
  | "unknown_account"
  /** The account is disabled: nothing is left to take out. */
  | "account_disabled"
  /** The account holds the instance-admin flag; an admin whose requests are all refused would still be the admin the instance keeps. */
  | "instance_admin"
  /** The end date is less than a day ahead. */
  | "until_too_soon";

export interface AccessModeRequest {
  /** A UUIDv7 generated by the caller (Q91): the identifier of the audit event the change writes. */
  readonly eventId: string;
  readonly change: AccessModeChange;
}

/**
 * The transaction as `setAccountAccessMode` uses it: an account-level tenant transaction of the account whose mode changes, and the
 * system operation that moves it, `sys_account_set_access_mode`, bound to it. `@slugbase/db` builds it inside the transaction a
 * composition already holds with `accountAccessModeTransaction(tx, newId)`.
 */
export interface AccountAccessModeTransaction {
  /** The account the transaction acts for. */
  readonly accountId: string;
  /** Undefined: the transaction must act in no workspace. */
  readonly workspaceId: string | undefined;
  /** Sets or clears the mode of the account of the transaction and writes the audit event, in the open transaction. */
  setAccessMode(request: AccessModeRequest): Promise<AccessModeOutcome>;
  /** A fresh UUIDv7, for the audit event. */
  newId(): string;
}

export interface SetAccountAccessModeRequest {
  /** The account whose mode changes; it must be the account the transaction acts for. */
  readonly accountId: string;
  /** `full` clears the mode; `exportOnly` sets it. `disabled` is not a mode this service sets. */
  readonly mode: "full" | "exportOnly";
  /** Required for `exportOnly`, at least a day ahead; refused for `full`. */
  readonly until?: Date;
  /** Required for `exportOnly`; refused for `full`. */
  readonly endAction?: ExportOnlyEndAction;
}

/** Thrown when the request does not fit the transaction, which leaves the transaction to roll back. */
export class AccountAccessModeError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "AccountAccessModeError";
  }
}

/** The change a request names; a request that is not well formed is a `RangeError`, before anything is written. */
export function accessModeChangeOf(request: Pick<SetAccountAccessModeRequest, "mode" | "until" | "endAction">): AccessModeChange {
  if (request.mode === "full") {
    if (request.until !== undefined || request.endAction !== undefined) {
      throw new RangeError("the full access mode carries no end date and no end action");
    }
    return { mode: "full" };
  }
  const { until, endAction } = request;
  if (until === undefined || Number.isNaN(until.getTime())) {
    throw new RangeError("the export-only access mode needs an end date");
  }
  if (endAction === undefined || !EXPORT_ONLY_END_ACTIONS.includes(endAction)) {
    throw new RangeError("the export-only access mode needs the end action disable or delete");
  }
  return { mode: "exportOnly", until, endAction };
}

/**
 * Sets (`exportOnly`, with an end date at least a day ahead and the end action) or clears (`full`) the access mode of the account
 * the transaction acts for, and writes the audit event, actor the system, in the same transaction (`sys_account_set_access_mode`).
 * It opens no transaction and throws `AccountAccessModeError`, which leaves the transaction to roll back, when the transaction is
 * not an account-level transaction of `request.accountId`. A refusal of the rule (`account_disabled`, `instance_admin`,
 * `until_too_soon`) and a repeat (`unchanged`) change nothing and are answered as the outcome. The service does not email the
 * account: the composition that calls it decides whether and how to tell it. CE itself never calls it.
 */
export async function setAccountAccessMode(
  tx: AccountAccessModeTransaction,
  request: SetAccountAccessModeRequest,
): Promise<{ readonly outcome: AccessModeOutcome }> {
  if (tx.workspaceId !== undefined || tx.accountId.toLowerCase() !== request.accountId.toLowerCase()) {
    throw new AccountAccessModeError("the transaction does not act at account level for the account of the request");
  }
  const change = accessModeChangeOf(request);
  return { outcome: await tx.setAccessMode({ eventId: tx.newId(), change }) };
}

/** What the database answered to the end of a period. `blocked` and `unavailable` end nothing. */
export type AccessModeEndStoreOutcome = "disabled" | "deleted" | "not_due" | "blocked" | "unavailable";

export interface AccessModeEndRequest {
  /** A UUIDv7 generated by the caller: the identifier of the `instance.account_export_only_ended` event. */
  readonly eventId: string;
  readonly action: ExportOnlyEndAction;
  /** For `delete`: the workspaces of the scope where the account is the only member, which go with it. */
  readonly soleWorkspaceIds: readonly string[];
  /** For `delete`: queued in the transaction that deletes the account, and only when it does. */
  readonly events: readonly DomainEvent<"account.deleted">[];
}

/** The stores of the end of a period, bound to the account-level transaction of the account whose period ends. */
export interface AccessModeEndStore {
  /** The scope of deleting the account, read under the locks that keep it true for the rest of the transaction. */
  scope(): Promise<AccountDeletionScope>;
  /**
   * Ends the period with `action` once its end date has passed (`sys_account_access_mode_end`): `disable` disables the account and
   * deletes its sessions; `delete` deletes it as `DELETE /me` does and queues the `workspace.delete` job of each of
   * `soleWorkspaceIds` and `events`. Writes the audit event in the same call. Anything but `disabled` and `deleted` changes nothing.
   */
  end(request: AccessModeEndRequest): Promise<AccessModeEndStoreOutcome>;
}

export interface AccessModeEndDependencies {
  readonly store: AccessModeEndStore;
  /** A fresh UUIDv7. */
  readonly newId: () => string;
}

export type AccessModeEndOutcome =
  /** The account is disabled; `deletionBlocked` is true when its end action was `delete` and it could not be deleted yet. */
  | { readonly kind: "disabled"; readonly deletionBlocked: boolean }
  /** The account is deleted; `workspaces` were deleted with it. */
  | { readonly kind: "deleted"; readonly workspaces: readonly AccountDeletionWorkspace[] }
  /** There was nothing to end: the period had not ended, or another run ended it. */
  | { readonly kind: "not_due" }
  /** The workspaces of the account changed under the deletion; nothing was written, and the next run tries again. */
  | { readonly kind: "unavailable" };

/**
 * Ends the export-only period of the account the store is bound to, once its end date has passed, with `endAction`. A run that finds the period ended
 * already changes nothing, so a job that runs twice acts once. `delete` follows the rules of `DELETE /me` that do not ask a person
 * (doc 02 section 2.10): the account is deleted with the workspaces where it is the only member, and the memberships elsewhere end
 * and its content there stays ownerless. When it is the only owner of a workspace that has other members, or the last enabled
 * instance admin, ownership cannot be resolved by a job, so the account is disabled instead: its access ends on the date and its data
 * stays, for an instance admin to resolve and delete. The deletion veto of a composition (doc 01 section 13.2) is not asked: the end
 * action was chosen by whoever set the mode.
 */
export async function endAccessMode(
  { store, newId }: AccessModeEndDependencies,
  ask: { readonly accountId: string; readonly endAction: ExportOnlyEndAction },
): Promise<AccessModeEndOutcome> {
  const disable = async (deletionBlocked: boolean): Promise<AccessModeEndOutcome> => {
    const outcome = await store.end({ eventId: newId(), action: "disable", soleWorkspaceIds: [], events: [] });
    switch (outcome) {
      case "disabled":
        return { kind: "disabled", deletionBlocked };
      case "not_due":
        return { kind: "not_due" };
      default:
        return { kind: "unavailable" };
    }
  };
  if (ask.endAction === "disable") {
    return disable(false);
  }
  const { blocking, soleMember, lastInstanceAdmin } = await store.scope();
  if (blocking.length > 0 || lastInstanceAdmin) {
    return disable(true);
  }
  const outcome = await store.end({
    eventId: newId(),
    action: "delete",
    soleWorkspaceIds: soleMember.map((workspace) => workspace.id),
    events: [{ eventId: newId(), name: "account.deleted", payload: { accountId: ask.accountId } }],
  });
  switch (outcome) {
    case "deleted":
      return { kind: "deleted", workspaces: soleMember };
    case "blocked":
      return disable(true);
    case "not_due":
      return { kind: "not_due" };
    default:
      return { kind: "unavailable" };
  }
}
