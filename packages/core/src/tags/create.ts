import type { TagRenameRequest, TagRenameResult } from "./rename.ts";

// Creating a tag (doc 02 section 7.2, doc 04 section 10.7, doc 10 T2). A tag is its owner's and nobody else's: the store creates it for
// the account of the transaction and every later read, rename and deletion names that owner. The name is stored as entered, with the
// whitespace around it removed, and is unique per owner without regard to case. The service checks the length before anything is
// written; a name that the owner already uses, however it is spelled, is refused by the store, which is the only place that can judge
// it under concurrent creations.

/** The longest tag name, in characters (doc 02 section 7.2). */
export const TAG_NAME_MAX_LENGTH = 40;

/** A tag as its owner sees it. */
export interface TagRecord {
  readonly id: string;
  /** The name as the owner entered it, without surrounding whitespace. */
  readonly name: string;
  /** How many of the owner's bookmarks carry the tag; plan-archived bookmarks are not counted. */
  readonly bookmarkCount: number;
  readonly createdAt: Date;
}

/** What the store writes for a new tag. */
export interface NewTag {
  /** A UUIDv7 generated by the caller (Q91). */
  readonly id: string;
  /** The member who creates it and owns it; the account of the transaction. */
  readonly ownerId: string;
  readonly name: string;
}

export type TagSort = "name" | "count";

export const TAG_SORTS: readonly TagSort[] = ["name", "count"];

export type TagStoreCreationResult =
  | { readonly kind: "created"; readonly tag: TagRecord }
  /** The owner already has a tag of that name, spelled in any case. */
  | { readonly kind: "name_taken" };

/** The place after which a page resumes: the last tag of the previous page. The count is given for the sort by count and for no other. */
export interface TagPosition {
  readonly count: number | undefined;
  readonly name: string;
  readonly id: string;
}

export interface TagListRequest {
  readonly ownerId: string;
  readonly sort: TagSort;
  /** The page starts after this place; the first page when undefined. */
  readonly after: TagPosition | undefined;
  readonly limit: number;
}

export interface TagStore {
  /** Inserts the tag for its owner in the workspace of the transaction. Nothing is written for `name_taken`. */
  create(tag: NewTag): Promise<TagStoreCreationResult>;
  /** The next `request.limit` tags that `ownerId` owns in the workspace of the transaction with the number of bookmarks each carries, in the order of `sort`, after `request.after`. */
  list(request: TagListRequest): Promise<readonly TagRecord[]>;
  /** How many tags `ownerId` owns in the workspace of the transaction, but at most `limit`. */
  count(ownerId: string, limit: number): Promise<number>;
  /**
   * Gives the tag that `request.ownerId` owns the name `request.name`. A name the tag has already, spelled exactly so, is `unchanged`;
   * the same name in another case is a rename. `name_taken` when the owner has another tag of that name; `not_found` for a tag the
   * owner does not own, whoever does, and one that does not exist.
   */
  rename(request: TagRenameRequest): Promise<TagRenameResult>;
  /** Deletes the tag that `request.ownerId` owns together with its links to bookmarks; false when the owner owns no such tag. */
  remove(request: { readonly tagId: string; readonly ownerId: string }): Promise<boolean>;
}

export interface TagCreationDependencies {
  readonly store: Pick<TagStore, "create">;
  /** Generates the identifier of a new tag: a UUIDv7. */
  readonly newId: () => string;
}

export interface TagCreationAsk {
  /** The member who creates the tag. */
  readonly accountId: string;
  readonly name: string;
}

export type TagCreationOutcome =
  | { readonly kind: "created"; readonly tag: TagRecord }
  | { readonly kind: "invalid_name"; readonly reason: TagNameRefusal }
  | { readonly kind: "name_taken" };

export type TagNameRefusal = "empty" | "too_long";

/** The name as it is stored, or the reason it is refused: empty, or longer than 40 characters, once the whitespace around it is removed. */
export function normalizeTagName(name: string): { readonly name: string } | { readonly refusal: TagNameRefusal } {
  const trimmed = name.trim();
  // Characters as the database counts them (`length()` counts code points), so a surrogate pair is one.
  const length = trimmed.replace(/[\uD800-\uDBFF][\uDC00-\uDFFF]/g, "_").length;
  if (length < 1) {
    return { refusal: "empty" };
  }
  return length > TAG_NAME_MAX_LENGTH ? { refusal: "too_long" } : { name: trimmed };
}

export async function createTag({ store, newId }: TagCreationDependencies, ask: TagCreationAsk): Promise<TagCreationOutcome> {
  const normalized = normalizeTagName(ask.name);
  if ("refusal" in normalized) {
    return { kind: "invalid_name", reason: normalized.refusal };
  }
  return store.create({ id: newId(), ownerId: ask.accountId.toLowerCase(), name: normalized.name });
}
