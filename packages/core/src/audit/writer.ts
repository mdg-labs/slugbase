import { AuditMetadataError, isAuditAction, isAuditIdentifier, parseAuditMetadata, type AuditAction, type AuditMetadata } from "./catalog.ts";

// The audit writer (doc 05 section 2.9, doc 01 section 4 step 12): validates an event against the catalog
// and hands the row to the store of the transaction that makes the change it records, so the event exists
// exactly when the change does. The store is bound to that transaction by whoever opens it; the writer
// opens none and swallows no failure of the store.

/** Who made the change. The label is the display name at the time and is never rewritten. */
export type AuditActor =
  | { readonly type: "account"; readonly accountId: string; readonly label: string }
  | { readonly type: "api_token"; readonly accountId: string; readonly tokenId: string; readonly label: string }
  | { readonly type: "system"; readonly label: string };

export interface AuditEventInput<Name extends AuditAction = AuditAction> {
  readonly action: Name;
  /** The workspace whose log records the event. */
  readonly workspaceId: string;
  readonly actor: AuditActor;
  /** What the change is about; left out for an event without a target. */
  readonly entity?: { readonly type: string; readonly id: string };
  readonly metadata: AuditMetadata<Name>;
  /** The coarse network of the request (`a.b.0.0/16` or an IPv6 `/48`), null when unknown. */
  readonly ipPrefix: string | null;
}

/** The row of `audit_events`, validated. */
export interface AuditRecord {
  /** A UUIDv7 generated by the caller (Q91). */
  readonly id: string;
  readonly workspaceId: string;
  readonly actorType: AuditActor["type"];
  readonly actorAccountId: string | null;
  readonly actorLabel: string;
  readonly actorTokenId: string | null;
  readonly action: AuditAction;
  readonly entityType: string | null;
  readonly entityId: string | null;
  readonly metadata: Readonly<Record<string, string>>;
  readonly ipPrefix: string | null;
}

export interface AuditStore {
  /** Inserts the row in the transaction the store is bound to. */
  insert(record: AuditRecord): Promise<void>;
}

const MAX_LABEL_LENGTH = 200;
const MAX_ENTITY_TYPE_LENGTH = 64;

function checked(valid: boolean, problem: string): void {
  if (!valid) {
    throw new AuditMetadataError(problem);
  }
}

/** The record of `event`, or a thrown `AuditMetadataError` naming what the catalog refuses; nothing is written. */
export function prepareAuditRecord<Name extends AuditAction>(event: AuditEventInput<Name>, newId: () => string): AuditRecord {
  checked(isAuditAction(event.action), "names an action outside the catalog");
  checked(isAuditIdentifier(event.workspaceId), "has no valid workspace identifier");
  const label = event.actor.label.trim();
  checked(label !== "" && Array.from(label).length <= MAX_LABEL_LENGTH, "has no valid actor label");
  if (event.actor.type !== "system") {
    checked(isAuditIdentifier(event.actor.accountId), "has no valid actor account identifier");
  }
  if (event.actor.type === "api_token") {
    checked(isAuditIdentifier(event.actor.tokenId), "has no valid actor token identifier");
  }
  if (event.entity !== undefined) {
    checked(event.entity.type !== "" && Array.from(event.entity.type).length <= MAX_ENTITY_TYPE_LENGTH, "has no valid entity type");
    checked(isAuditIdentifier(event.entity.id), "has no valid entity identifier");
  }
  const metadata = parseAuditMetadata(event.action, event.metadata);
  const actor = event.actor;
  return {
    id: newId(),
    workspaceId: event.workspaceId,
    actorType: actor.type,
    actorAccountId: actor.type === "system" ? null : actor.accountId,
    actorLabel: label,
    actorTokenId: actor.type === "api_token" ? actor.tokenId : null,
    action: event.action,
    entityType: event.entity?.type ?? null,
    entityId: event.entity?.id ?? null,
    metadata: { ...metadata },
    ipPrefix: event.ipPrefix,
  };
}

export interface AuditWriterDependencies {
  readonly store: AuditStore;
  /** A fresh UUIDv7. */
  readonly newId: () => string;
}

export interface AuditWriter {
  /** Validates the event and inserts it through the store; rejects, writing nothing, when the catalog refuses it. */
  write<Name extends AuditAction>(event: AuditEventInput<Name>): Promise<void>;
}

export function createAuditWriter({ store, newId }: AuditWriterDependencies): AuditWriter {
  return {
    write: async (event) => {
      await store.insert(prepareAuditRecord(event, newId));
    },
  };
}
